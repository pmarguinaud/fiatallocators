MODULE PEAK_CORE_MOD

! Plain ALLOCATE/DEALLOCATE of each array (as a byte buffer), with the peak of the memory in use
! recorded and printed by DESTROY. Shared by PEAK_CPU and PEAK_GPU. Arrays can be freed in any
! order; the side is ignored. KSIZE is ignored.
! The concrete classes may override ON_ALLOC / ON_FREE (PEAK_GPU creates the device copy there).

USE ISO_C_BINDING
USE ISO_FORTRAN_ENV, ONLY : OUTPUT_UNIT
USE PARKIND1, ONLY : JPIM, JPIB
USE ALLOCATOR_BASE_MOD, ONLY : ALLOCATOR_BASE
USE STACK_CORE_MOD, ONLY : MIB

IMPLICIT NONE

PRIVATE
PUBLIC :: PEAK_BASE

#include "abor1.intfb.h"

TYPE PEAK_ENTRY
  INTEGER (KIND=C_INT8_T), POINTER :: IBUF (:) => NULL()
  INTEGER (KIND=C_INTPTR_T) :: IADDR = 0
  INTEGER (KIND=JPIB) :: INBYTES = 0
END TYPE

TYPE, ABSTRACT, EXTENDS (ALLOCATOR_BASE) :: PEAK_BASE
  TYPE (PEAK_ENTRY), ALLOCATABLE :: YE (:)      ! live arrays
  INTEGER (KIND=JPIM) :: N = 0
  INTEGER (KIND=JPIB) :: IUSED = 0, IPEAK = 0   ! bytes in use, peak
  INTEGER (KIND=JPIB) :: INALLOC = 0
  INTEGER (KIND=JPIM) :: INZERO = 0             ! live zero-size arrays
  INTEGER (KIND=C_INT8_T), POINTER :: IZERO (:) => NULL()   ! address for zero-size arrays
CONTAINS
  PROCEDURE :: ALLOC_BYTES => PEAK_ALLOC_BYTES
  PROCEDURE :: FREE_BYTES => PEAK_FREE_BYTES
  PROCEDURE :: REPORT => PEAK_REPORT
  PROCEDURE :: PEAK_USED => PEAK_PEAK_USED
  PROCEDURE :: ON_ALLOC => PEAK_ON_ALLOC
  PROCEDURE :: ON_FREE => PEAK_ON_FREE
  PROCEDURE :: PEAK_OPEN, PEAK_CLOSE
END TYPE PEAK_BASE

CONTAINS

SUBROUTINE PEAK_OPEN (SELF)

CLASS (PEAK_BASE), INTENT (INOUT) :: SELF

IF (.NOT. ALLOCATED (SELF%YE)) ALLOCATE (SELF%YE (64))
IF (.NOT. ASSOCIATED (SELF%IZERO)) ALLOCATE (SELF%IZERO (1))
SELF%N = 0
SELF%IUSED = 0
SELF%IPEAK = 0
SELF%INALLOC = 0
SELF%INZERO = 0
SELF%LINIT = .TRUE.

END SUBROUTINE PEAK_OPEN

SUBROUTINE PEAK_CLOSE (SELF)

! Release the arrays still allocated (warning if verbose), print the report

CLASS (PEAK_BASE), INTENT (INOUT) :: SELF

INTEGER (KIND=JPIM) :: J

IF ((SELF%N > 0 .OR. SELF%INZERO > 0) .AND. SELF%LVERBOSE) WRITE (OUTPUT_UNIT, '(A,A,I0,A)') &
  & TRIM (SELF%CNAME), '%DESTROY: warning: ', SELF%N + SELF%INZERO, ' array(s) still allocated; released anyway'
DO J = 1, SELF%N
  CALL SELF%ON_FREE (SELF%YE (J)%IADDR, SELF%YE (J)%INBYTES)
  DEALLOCATE (SELF%YE (J)%IBUF)
ENDDO
SELF%N = 0
SELF%INZERO = 0
CALL SELF%REPORT
IF (ASSOCIATED (SELF%IZERO)) DEALLOCATE (SELF%IZERO)
SELF%LINIT = .FALSE.

END SUBROUTINE PEAK_CLOSE

FUNCTION PEAK_ALLOC_BYTES (SELF, KBYTES, KSIDE, LDZERO) RESULT (KADDR)

CLASS (PEAK_BASE), INTENT (INOUT) :: SELF
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES
INTEGER (KIND=JPIM), INTENT (IN) :: KSIDE
LOGICAL, INTENT (IN) :: LDZERO
INTEGER (KIND=C_INTPTR_T) :: KADDR

TYPE (PEAK_ENTRY), ALLOCATABLE :: YLTMP (:)

SELF%INALLOC = SELF%INALLOC + 1
IF (LDZERO) THEN
  SELF%INZERO = SELF%INZERO + 1
  KADDR = TRANSFER (C_LOC (SELF%IZERO), KADDR)
  RETURN
ENDIF

IF (SELF%N == SIZE (SELF%YE)) THEN
  ALLOCATE (YLTMP (2 * SIZE (SELF%YE)))
  YLTMP (1:SELF%N) = SELF%YE (1:SELF%N)
  CALL MOVE_ALLOC (YLTMP, SELF%YE)
ENDIF
SELF%N = SELF%N + 1
ASSOCIATE (YLE => SELF%YE (SELF%N))
  ALLOCATE (YLE%IBUF (KBYTES))
  YLE%IADDR = TRANSFER (C_LOC (YLE%IBUF), YLE%IADDR)
  YLE%INBYTES = KBYTES
  KADDR = YLE%IADDR
END ASSOCIATE
CALL SELF%ON_ALLOC (KADDR, KBYTES)

SELF%IUSED = SELF%IUSED + KBYTES
SELF%IPEAK = MAX (SELF%IPEAK, SELF%IUSED)
IF (SELF%LVERBOSE) WRITE (OUTPUT_UNIT, '(A,A,I0,A,Z0,A,F0.1,A)') TRIM (SELF%CNAME), '%ALLOCATE: ', &
  & KBYTES, ' bytes, host 0x', KADDR, '; in use ', MIB (SELF%IUSED), ' MiB'

END FUNCTION PEAK_ALLOC_BYTES

SUBROUTINE PEAK_FREE_BYTES (SELF, KADDR, LDZERO)

CLASS (PEAK_BASE), INTENT (INOUT) :: SELF
INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KADDR
LOGICAL, INTENT (IN) :: LDZERO

INTEGER (KIND=JPIM) :: J
CHARACTER (LEN=256) :: CLMESS

IF (LDZERO) THEN
  IF (SELF%INZERO == 0) CALL ABOR1 (TRIM (SELF%CNAME)//'%DEALLOCATE: no zero-size array allocated')
  SELF%INZERO = SELF%INZERO - 1
  RETURN
ENDIF

! Most recent first: LIFO use is the common case
DO J = SELF%N, 1, -1
  IF (SELF%YE (J)%IADDR == KADDR) EXIT
ENDDO
IF (J < 1) THEN
  WRITE (CLMESS, '(A,A,Z0,A)') TRIM (SELF%CNAME), '%DEALLOCATE: array at host address 0x', KADDR, &
    & ' was not allocated by this allocator'
  CALL ABOR1 (TRIM (CLMESS))
ENDIF

CALL SELF%ON_FREE (KADDR, SELF%YE (J)%INBYTES)
SELF%IUSED = SELF%IUSED - SELF%YE (J)%INBYTES
IF (SELF%LVERBOSE) WRITE (OUTPUT_UNIT, '(A,A,I0,A,Z0,A,F0.1,A)') TRIM (SELF%CNAME), '%DEALLOCATE: ', &
  & SELF%YE (J)%INBYTES, ' bytes, host 0x', KADDR, '; in use ', MIB (SELF%IUSED), ' MiB'
DEALLOCATE (SELF%YE (J)%IBUF)
SELF%YE (J) = SELF%YE (SELF%N)
NULLIFY (SELF%YE (SELF%N)%IBUF)
SELF%N = SELF%N - 1

END SUBROUTINE PEAK_FREE_BYTES

SUBROUTINE PEAK_ON_ALLOC (SELF, KADDR, KBYTES)

CLASS (PEAK_BASE), INTENT (INOUT) :: SELF
INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KADDR
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

END SUBROUTINE PEAK_ON_ALLOC

SUBROUTINE PEAK_ON_FREE (SELF, KADDR, KBYTES)

CLASS (PEAK_BASE), INTENT (INOUT) :: SELF
INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KADDR
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

END SUBROUTINE PEAK_ON_FREE

SUBROUTINE PEAK_REPORT (SELF, KUNIT)

CLASS (PEAK_BASE), INTENT (IN) :: SELF
INTEGER, INTENT (IN), OPTIONAL :: KUNIT

INTEGER :: IUNIT

IUNIT = OUTPUT_UNIT
IF (PRESENT (KUNIT)) IUNIT = KUNIT
WRITE (IUNIT, '(A,A,F0.1,A,I0,A,I0,A)') TRIM (SELF%CNAME), ': peak memory ', MIB (SELF%IPEAK), &
  & ' MiB (', SELF%IPEAK, ' bytes); ', SELF%INALLOC, ' allocations'

END SUBROUTINE PEAK_REPORT

FUNCTION PEAK_PEAK_USED (SELF) RESULT (KBYTES)

CLASS (PEAK_BASE), INTENT (IN) :: SELF
INTEGER (KIND=JPIB) :: KBYTES

KBYTES = SELF%IPEAK

END FUNCTION PEAK_PEAK_USED

END MODULE PEAK_CORE_MOD

MODULE HOST_HELPERS_MOD

! Host memory helpers, on top of libc (Linux): reservation of virtual memory (mmap with
! MAP_NORESERVE: only the pages touched become memory), physical memory size, memset.
! Addresses are INTEGER (KIND=C_INTPTR_T).

USE ISO_C_BINDING
USE PARKIND1, ONLY : JPIB

IMPLICIT NONE

PRIVATE
PUBLIC :: HOST_RESERVE, HOST_RELEASE, HOST_MEMORY_SIZE, HOST_MEMSET

#include "abor1.intfb.h"

! Linux values, identical on x86_64 and aarch64
INTEGER (KIND=C_INT), PARAMETER :: PROT_READ = 1, PROT_WRITE = 2
INTEGER (KIND=C_INT), PARAMETER :: MAP_PRIVATE = 2, MAP_ANONYMOUS = 32, MAP_NORESERVE = 16384
INTEGER (KIND=C_INT), PARAMETER :: SC_PAGESIZE = 30, SC_PHYS_PAGES = 85

INTERFACE

FUNCTION C_MMAP (ADDR, LEN, PROT, FLAGS, FD, OFFSET) BIND (C, NAME='mmap') RESULT (P)
  IMPORT
  TYPE (C_PTR), VALUE :: ADDR
  INTEGER (KIND=C_SIZE_T), VALUE :: LEN
  INTEGER (KIND=C_INT), VALUE :: PROT, FLAGS, FD
  INTEGER (KIND=C_LONG), VALUE :: OFFSET
  TYPE (C_PTR) :: P
END FUNCTION

FUNCTION C_MUNMAP (ADDR, LEN) BIND (C, NAME='munmap') RESULT (IRC)
  IMPORT
  TYPE (C_PTR), VALUE :: ADDR
  INTEGER (KIND=C_SIZE_T), VALUE :: LEN
  INTEGER (KIND=C_INT) :: IRC
END FUNCTION

FUNCTION C_SYSCONF (NAME) BIND (C, NAME='sysconf') RESULT (IVAL)
  IMPORT
  INTEGER (KIND=C_INT), VALUE :: NAME
  INTEGER (KIND=C_LONG) :: IVAL
END FUNCTION

FUNCTION C_MEMSET (S, C, N) BIND (C, NAME='memset') RESULT (P)
  IMPORT
  TYPE (C_PTR), VALUE :: S
  INTEGER (KIND=C_INT), VALUE :: C
  INTEGER (KIND=C_SIZE_T), VALUE :: N
  TYPE (C_PTR) :: P
END FUNCTION

END INTERFACE

CONTAINS

FUNCTION HOST_RESERVE (KBYTES) RESULT (KADDR)

! Reserve KBYTES of virtual memory (page aligned); no memory is used until pages are touched

INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES
INTEGER (KIND=C_INTPTR_T) :: KADDR

TYPE (C_PTR) :: P
CHARACTER (LEN=128) :: CLMESS

P = C_MMAP (C_NULL_PTR, INT (KBYTES, C_SIZE_T), IOR (PROT_READ, PROT_WRITE), &
          & IOR (IOR (MAP_PRIVATE, MAP_ANONYMOUS), MAP_NORESERVE), -1_C_INT, 0_C_LONG)
KADDR = TRANSFER (P, KADDR)
IF (KADDR == -1_C_INTPTR_T) THEN
  WRITE (CLMESS, '(A,I0,A)') 'HOST_RESERVE: mmap of ', KBYTES, ' bytes failed'
  CALL ABOR1 (TRIM (CLMESS))
ENDIF

END FUNCTION HOST_RESERVE

SUBROUTINE HOST_RELEASE (KADDR, KBYTES)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KADDR
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

IF (C_MUNMAP (TRANSFER (KADDR, C_NULL_PTR), INT (KBYTES, C_SIZE_T)) /= 0) &
  & CALL ABOR1 ('HOST_RELEASE: munmap failed')

END SUBROUTINE HOST_RELEASE

FUNCTION HOST_MEMORY_SIZE () RESULT (KBYTES)

! Physical memory of the node, in bytes

INTEGER (KIND=JPIB) :: KBYTES

KBYTES = INT (C_SYSCONF (SC_PHYS_PAGES), JPIB) * INT (C_SYSCONF (SC_PAGESIZE), JPIB)

END FUNCTION HOST_MEMORY_SIZE

SUBROUTINE HOST_MEMSET (KADDR, KBYTE, KBYTES)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KADDR
INTEGER, INTENT (IN) :: KBYTE
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

TYPE (C_PTR) :: P

P = C_MEMSET (TRANSFER (KADDR, C_NULL_PTR), INT (KBYTE, C_INT), INT (KBYTES, C_SIZE_T))

END SUBROUTINE HOST_MEMSET

END MODULE HOST_HELPERS_MOD

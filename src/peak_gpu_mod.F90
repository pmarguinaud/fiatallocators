MODULE PEAK_GPU_MOD

! PEAK_GPU: each array is allocated on the host (plain ALLOCATE) and created on the device
! (acc_create, i.e. ENTER DATA CREATE; OpenMP on AMD later); DEALLOCATE deletes the device copy
! (EXIT DATA DELETE) and the host array. DESTROY prints the peak memory used.

USE ISO_C_BINDING
USE PARKIND1, ONLY : JPIB
USE PEAK_CORE_MOD, ONLY : PEAK_BASE
USE GPU_HELPERS_MOD, ONLY : GPU_INIT, GPU_CREATE, GPU_DELETE

IMPLICIT NONE

PRIVATE
PUBLIC :: PEAK_GPU

TYPE, EXTENDS (PEAK_BASE) :: PEAK_GPU
CONTAINS
  PROCEDURE :: INIT => PKG_INIT
  PROCEDURE :: DESTROY => PKG_DESTROY
  PROCEDURE :: ON_ALLOC => PKG_ON_ALLOC
  PROCEDURE :: ON_FREE => PKG_ON_FREE
  FINAL :: PKG_FINAL
END TYPE PEAK_GPU

CONTAINS

SUBROUTINE PKG_INIT (SELF, KSIZE, LDDEBUG, LDVERBOSE)

CLASS (PEAK_GPU), INTENT (INOUT) :: SELF
INTEGER (KIND=JPIB), INTENT (IN) :: KSIZE
LOGICAL, INTENT (IN), OPTIONAL :: LDDEBUG, LDVERBOSE

CALL SELF%SET_OPTIONS ('PEAK_GPU', LDDEBUG, LDVERBOSE)
CALL GPU_INIT
CALL SELF%PEAK_OPEN

END SUBROUTINE PKG_INIT

SUBROUTINE PKG_ON_ALLOC (SELF, KADDR, KBYTES)

CLASS (PEAK_GPU), INTENT (INOUT) :: SELF
INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KADDR
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

CALL GPU_CREATE (KADDR, KBYTES)

END SUBROUTINE PKG_ON_ALLOC

SUBROUTINE PKG_ON_FREE (SELF, KADDR, KBYTES)

CLASS (PEAK_GPU), INTENT (INOUT) :: SELF
INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KADDR
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

CALL GPU_DELETE (KADDR, KBYTES)

END SUBROUTINE PKG_ON_FREE

SUBROUTINE PKG_DESTROY (SELF)

CLASS (PEAK_GPU), INTENT (INOUT) :: SELF

IF (SELF%LINIT) CALL SELF%PEAK_CLOSE

END SUBROUTINE PKG_DESTROY

SUBROUTINE PKG_FINAL (SELF)

TYPE (PEAK_GPU), INTENT (INOUT) :: SELF

IF (SELF%LINIT) CALL SELF%DESTROY

END SUBROUTINE PKG_FINAL

END MODULE PEAK_GPU_MOD

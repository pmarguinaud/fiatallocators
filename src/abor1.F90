SUBROUTINE ABOR1 (CDTEXT)

! Abort with a message. Same name and interface as FIAT's ABOR1, which can replace it later.

USE ISO_FORTRAN_ENV, ONLY : ERROR_UNIT, OUTPUT_UNIT

IMPLICIT NONE

CHARACTER (LEN=*), INTENT (IN) :: CDTEXT

FLUSH (OUTPUT_UNIT)
WRITE (ERROR_UNIT, '(A,A)') 'ABOR1: ', CDTEXT
FLUSH (ERROR_UNIT)
ERROR STOP 1

END SUBROUTINE ABOR1

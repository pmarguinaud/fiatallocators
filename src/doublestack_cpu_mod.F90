MODULE DOUBLESTACK_CPU_MOD

! DOUBLESTACK_CPU: double stack in one large buffer of host virtual memory (mmap MAP_NORESERVE).
! Only the pages touched become memory, so the buffer can be as large as the node memory.
! KSIZE: size of the buffer in bytes; 0 = physical memory of the node.

USE ISO_C_BINDING
USE PARKIND1, ONLY : JPIB
USE ALLOCATOR_PARAMS_MOD, ONLY : ALLOC_ALIGNMENT
USE STACK_CORE_MOD, ONLY : STACK_BASE
USE HOST_HELPERS_MOD, ONLY : HOST_RESERVE, HOST_RELEASE, HOST_MEMORY_SIZE

IMPLICIT NONE

PRIVATE
PUBLIC :: DOUBLESTACK_CPU

TYPE, EXTENDS (STACK_BASE) :: DOUBLESTACK_CPU
CONTAINS
  PROCEDURE :: INIT => DSC_INIT
  PROCEDURE :: DESTROY => DSC_DESTROY
  FINAL :: DSC_FINAL
END TYPE DOUBLESTACK_CPU

CONTAINS

SUBROUTINE DSC_INIT (SELF, KSIZE, LDDEBUG, LDVERBOSE)

CLASS (DOUBLESTACK_CPU), INTENT (INOUT) :: SELF
INTEGER (KIND=JPIB), INTENT (IN) :: KSIZE
LOGICAL, INTENT (IN), OPTIONAL :: LDDEBUG, LDVERBOSE

INTEGER (KIND=JPIB) :: ISIZE

CALL SELF%SET_OPTIONS ('DOUBLESTACK_CPU', LDDEBUG, LDVERBOSE)
ISIZE = KSIZE
IF (ISIZE == 0) ISIZE = HOST_MEMORY_SIZE ()
ISIZE = ISIZE / ALLOC_ALIGNMENT * ALLOC_ALIGNMENT
CALL SELF%STACK_OPEN (HOST_RESERVE (ISIZE), ISIZE)

END SUBROUTINE DSC_INIT

SUBROUTINE DSC_DESTROY (SELF)

CLASS (DOUBLESTACK_CPU), INTENT (INOUT) :: SELF

IF (.NOT. SELF%LINIT) RETURN
CALL SELF%STACK_CLOSE
CALL HOST_RELEASE (SELF%IHOST, SELF%ISIZE)

END SUBROUTINE DSC_DESTROY

SUBROUTINE DSC_FINAL (SELF)

TYPE (DOUBLESTACK_CPU), INTENT (INOUT) :: SELF

IF (SELF%LINIT) CALL SELF%DESTROY

END SUBROUTINE DSC_FINAL

END MODULE DOUBLESTACK_CPU_MOD

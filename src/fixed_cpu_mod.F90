MODULE FIXED_CPU_MOD

! FIXED_CPU: double stack in a host buffer of fixed size, allocated at once (ALLOCATE).
! KSIZE: size of the buffer in bytes (> 0). An allocation that does not fit aborts.
! DESTROY prints the buffer size and the peak actually used.

USE ISO_C_BINDING
USE PARKIND1, ONLY : JPIB
USE ALLOCATOR_PARAMS_MOD, ONLY : ALLOC_ALIGNMENT
USE STACK_CORE_MOD, ONLY : STACK_BASE

IMPLICIT NONE

PRIVATE
PUBLIC :: FIXED_CPU

#include "abor1.intfb.h"

TYPE, EXTENDS (STACK_BASE) :: FIXED_CPU
  INTEGER (KIND=C_INT8_T), POINTER :: IBUF (:) => NULL()   ! the buffer, with room for alignment
CONTAINS
  PROCEDURE :: INIT => FXC_INIT
  PROCEDURE :: DESTROY => FXC_DESTROY
  FINAL :: FXC_FINAL
END TYPE FIXED_CPU

CONTAINS

SUBROUTINE FXC_INIT (SELF, KSIZE, LDDEBUG, LDVERBOSE)

CLASS (FIXED_CPU), INTENT (INOUT) :: SELF
INTEGER (KIND=JPIB), INTENT (IN) :: KSIZE
LOGICAL, INTENT (IN), OPTIONAL :: LDDEBUG, LDVERBOSE

INTEGER (KIND=JPIB) :: ISIZE
INTEGER (KIND=C_INTPTR_T) :: IADDR, IALIGN

CALL SELF%SET_OPTIONS ('FIXED_CPU', LDDEBUG, LDVERBOSE)
IF (KSIZE <= 0) CALL ABOR1 ('FIXED_CPU%INIT: KSIZE must be > 0')
ISIZE = KSIZE / ALLOC_ALIGNMENT * ALLOC_ALIGNMENT
ALLOCATE (SELF%IBUF (ISIZE + ALLOC_ALIGNMENT))
IALIGN = INT (ALLOC_ALIGNMENT, C_INTPTR_T)
IADDR = TRANSFER (C_LOC (SELF%IBUF), IADDR)
IADDR = (IADDR + IALIGN - 1) / IALIGN * IALIGN
CALL SELF%STACK_OPEN (IADDR, ISIZE)

END SUBROUTINE FXC_INIT

SUBROUTINE FXC_DESTROY (SELF)

CLASS (FIXED_CPU), INTENT (INOUT) :: SELF

IF (.NOT. SELF%LINIT) RETURN
CALL SELF%STACK_CLOSE
DEALLOCATE (SELF%IBUF)

END SUBROUTINE FXC_DESTROY

SUBROUTINE FXC_FINAL (SELF)

TYPE (FIXED_CPU), INTENT (INOUT) :: SELF

IF (SELF%LINIT) CALL SELF%DESTROY

END SUBROUTINE FXC_FINAL

END MODULE FIXED_CPU_MOD

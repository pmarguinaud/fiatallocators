MODULE FIXED_GPU_MOD

! FIXED_GPU: double stack in a device buffer of fixed size, allocated at once by INIT (acc_malloc
! on NVIDIA, omp_target_alloc on AMD). KSIZE: size of the buffer in bytes (> 0). An
! allocation that does not fit aborts. DESTROY prints the buffer size and the peak actually used.
! As DOUBLESTACK_GPU, the arrays are host pointers into a host mirror mapped to the buffer.

USE ISO_C_BINDING
USE PARKIND1, ONLY : JPIB
USE ALLOCATOR_PARAMS_MOD, ONLY : ALLOC_ALIGNMENT, DEBUG_FILL_BYTE
USE STACK_CORE_MOD, ONLY : STACK_BASE
USE HOST_HELPERS_MOD, ONLY : HOST_RESERVE, HOST_RELEASE
USE GPU_HELPERS_MOD, ONLY : GPU_INIT, GPU_MALLOC, GPU_FREE, GPU_MAP_DATA, GPU_UNMAP_DATA, GPU_MEMSET

IMPLICIT NONE

PRIVATE
PUBLIC :: FIXED_GPU

#include "abor1.intfb.h"

TYPE, EXTENDS (STACK_BASE) :: FIXED_GPU
  INTEGER (KIND=C_INTPTR_T) :: IDEV = 0       ! device address of the buffer
CONTAINS
  PROCEDURE :: INIT => FXG_INIT
  PROCEDURE :: DESTROY => FXG_DESTROY
  PROCEDURE :: FILL => FXG_FILL
  FINAL :: FXG_FINAL
END TYPE FIXED_GPU

CONTAINS

SUBROUTINE FXG_INIT (SELF, KSIZE, LDDEBUG, LDVERBOSE)

CLASS (FIXED_GPU), INTENT (INOUT) :: SELF
INTEGER (KIND=JPIB), INTENT (IN) :: KSIZE
LOGICAL, INTENT (IN), OPTIONAL :: LDDEBUG, LDVERBOSE

INTEGER (KIND=JPIB) :: ISIZE
INTEGER (KIND=C_INTPTR_T) :: IHOST

CALL SELF%SET_OPTIONS ('FIXED_GPU', LDDEBUG, LDVERBOSE)
IF (KSIZE <= 0) CALL ABOR1 ('FIXED_GPU%INIT: KSIZE must be > 0')
CALL GPU_INIT
ISIZE = KSIZE / ALLOC_ALIGNMENT * ALLOC_ALIGNMENT
SELF%IDEV = GPU_MALLOC (ISIZE)
IHOST = HOST_RESERVE (ISIZE)
CALL GPU_MAP_DATA (IHOST, SELF%IDEV, ISIZE)
CALL SELF%STACK_OPEN (IHOST, ISIZE)

END SUBROUTINE FXG_INIT

SUBROUTINE FXG_FILL (SELF, KOFF, KBYTES)

CLASS (FIXED_GPU), INTENT (INOUT) :: SELF
INTEGER (KIND=JPIB), INTENT (IN) :: KOFF, KBYTES

CALL GPU_MEMSET (SELF%IDEV + INT (KOFF, C_INTPTR_T), DEBUG_FILL_BYTE, KBYTES)

END SUBROUTINE FXG_FILL

SUBROUTINE FXG_DESTROY (SELF)

CLASS (FIXED_GPU), INTENT (INOUT) :: SELF

IF (.NOT. SELF%LINIT) RETURN
CALL SELF%STACK_CLOSE
CALL GPU_UNMAP_DATA (SELF%IHOST)
CALL GPU_FREE (SELF%IDEV)
CALL HOST_RELEASE (SELF%IHOST, SELF%ISIZE)

END SUBROUTINE FXG_DESTROY

SUBROUTINE FXG_FINAL (SELF)

TYPE (FIXED_GPU), INTENT (INOUT) :: SELF

IF (SELF%LINIT) CALL SELF%DESTROY

END SUBROUTINE FXG_FINAL

END MODULE FIXED_GPU_MOD

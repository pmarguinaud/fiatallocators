MODULE PEAK_CPU_MOD

! PEAK_CPU: plain ALLOCATE/DEALLOCATE of each array; DESTROY prints the peak memory used.

USE PARKIND1, ONLY : JPIB
USE PEAK_CORE_MOD, ONLY : PEAK_BASE

IMPLICIT NONE

PRIVATE
PUBLIC :: PEAK_CPU

TYPE, EXTENDS (PEAK_BASE) :: PEAK_CPU
CONTAINS
  PROCEDURE :: INIT => PKC_INIT
  PROCEDURE :: DESTROY => PKC_DESTROY
  FINAL :: PKC_FINAL
END TYPE PEAK_CPU

CONTAINS

SUBROUTINE PKC_INIT (SELF, KSIZE, LDDEBUG, LDVERBOSE)

CLASS (PEAK_CPU), INTENT (INOUT) :: SELF
INTEGER (KIND=JPIB), INTENT (IN) :: KSIZE
LOGICAL, INTENT (IN), OPTIONAL :: LDDEBUG, LDVERBOSE

CALL SELF%SET_OPTIONS ('PEAK_CPU', LDDEBUG, LDVERBOSE)
CALL SELF%PEAK_OPEN

END SUBROUTINE PKC_INIT

SUBROUTINE PKC_DESTROY (SELF)

CLASS (PEAK_CPU), INTENT (INOUT) :: SELF

IF (SELF%LINIT) CALL SELF%PEAK_CLOSE

END SUBROUTINE PKC_DESTROY

SUBROUTINE PKC_FINAL (SELF)

TYPE (PEAK_CPU), INTENT (INOUT) :: SELF

IF (SELF%LINIT) CALL SELF%DESTROY

END SUBROUTINE PKC_FINAL

END MODULE PEAK_CPU_MOD

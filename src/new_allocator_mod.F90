MODULE NEW_ALLOCATOR_MOD

! Factory: CALL NEW_ALLOCATOR (YDALLOC, CDKIND, LDGPU, KSIZE [, LDDEBUG] [, LDVERBOSE])
!   CDKIND = 'doublestack', 'fixed' or 'peak'; LDGPU selects the GPU class.
!   YDALLOC: CLASS (ALLOCATOR_BASE), POINTER, allocated and initialised (INIT called).
! The caller ends with CALL YDALLOC%DESTROY and DEALLOCATE (YDALLOC).
! The GPU classes exist only when the library is built with WITH_GPU.

USE PARKIND1, ONLY : JPIB
USE ALLOCATOR_BASE_MOD, ONLY : ALLOCATOR_BASE
USE DOUBLESTACK_CPU_MOD, ONLY : DOUBLESTACK_CPU
USE FIXED_CPU_MOD, ONLY : FIXED_CPU
USE PEAK_CPU_MOD, ONLY : PEAK_CPU
#ifdef WITH_GPU
USE DOUBLESTACK_GPU_MOD, ONLY : DOUBLESTACK_GPU
USE FIXED_GPU_MOD, ONLY : FIXED_GPU
USE PEAK_GPU_MOD, ONLY : PEAK_GPU
#endif

IMPLICIT NONE

PRIVATE
PUBLIC :: NEW_ALLOCATOR

#include "abor1.intfb.h"

CONTAINS

SUBROUTINE NEW_ALLOCATOR (YDALLOC, CDKIND, LDGPU, KSIZE, LDDEBUG, LDVERBOSE)

CLASS (ALLOCATOR_BASE), POINTER, INTENT (OUT) :: YDALLOC
CHARACTER (LEN=*), INTENT (IN) :: CDKIND
LOGICAL, INTENT (IN) :: LDGPU
INTEGER (KIND=JPIB), INTENT (IN) :: KSIZE
LOGICAL, INTENT (IN), OPTIONAL :: LDDEBUG, LDVERBOSE

NULLIFY (YDALLOC)
IF (.NOT. LDGPU) THEN
  SELECT CASE (CDKIND)
  CASE ('doublestack')
    ALLOCATE (DOUBLESTACK_CPU :: YDALLOC)
  CASE ('fixed')
    ALLOCATE (FIXED_CPU :: YDALLOC)
  CASE ('peak')
    ALLOCATE (PEAK_CPU :: YDALLOC)
  END SELECT
ELSE
#ifdef WITH_GPU
  SELECT CASE (CDKIND)
  CASE ('doublestack')
    ALLOCATE (DOUBLESTACK_GPU :: YDALLOC)
  CASE ('fixed')
    ALLOCATE (FIXED_GPU :: YDALLOC)
  CASE ('peak')
    ALLOCATE (PEAK_GPU :: YDALLOC)
  END SELECT
#else
  CALL ABOR1 ('NEW_ALLOCATOR: GPU allocator requested, but the library was built without GPU support')
#endif
ENDIF
IF (.NOT. ASSOCIATED (YDALLOC)) &
  & CALL ABOR1 ('NEW_ALLOCATOR: unknown kind "'//CDKIND//'" (doublestack, fixed or peak)')

CALL YDALLOC%INIT (KSIZE, LDDEBUG, LDVERBOSE)

END SUBROUTINE NEW_ALLOCATOR

END MODULE NEW_ALLOCATOR_MOD

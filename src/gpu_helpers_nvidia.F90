                            & BIND (C, NAME='cuMemAddressReserve')
  IMPORT
  INTEGER (KIND=C_INTPTR_T) :: IPTR
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE, IALIGN
  INTEGER (KIND=C_INTPTR_T), VALUE :: IADDR
  INTEGER (KIND=C_LONG_LONG), VALUE :: IFLAGS
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUMEMADDRESSFREE (IPTR, ISIZE) BIND (C, NAME='cuMemAddressFree')
  IMPORT
  INTEGER (KIND=C_INTPTR_T), VALUE :: IPTR
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUMEMCREATE (IHANDLE, ISIZE, YPROP, IFLAGS) BIND (C, NAME='cuMemCreate')
  IMPORT
  INTEGER (KIND=C_LONG_LONG) :: IHANDLE
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE
  TYPE (CUMEMALLOCATIONPROP) :: YPROP
  INTEGER (KIND=C_LONG_LONG), VALUE :: IFLAGS
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUMEMMAP (IPTR, ISIZE, IOFFSET, IHANDLE, IFLAGS) BIND (C, NAME='cuMemMap')
  IMPORT
  INTEGER (KIND=C_INTPTR_T), VALUE :: IPTR
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE, IOFFSET
  INTEGER (KIND=C_LONG_LONG), VALUE :: IHANDLE, IFLAGS
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUMEMRELEASE (IHANDLE) BIND (C, NAME='cuMemRelease')
  IMPORT
  INTEGER (KIND=C_LONG_LONG), VALUE :: IHANDLE
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUMEMSETACCESS (IPTR, ISIZE, YDESC, ICOUNT) BIND (C, NAME='cuMemSetAccess')
  IMPORT
  INTEGER (KIND=C_INTPTR_T), VALUE :: IPTR
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE
  TYPE (CUMEMACCESSDESC) :: YDESC
  INTEGER (KIND=C_SIZE_T), VALUE :: ICOUNT
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUMEMUNMAP (IPTR, ISIZE) BIND (C, NAME='cuMemUnmap')
  IMPORT
  INTEGER (KIND=C_INTPTR_T), VALUE :: IPTR
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUMEMSETD8 (IPTR, IVAL, ICOUNT) BIND (C, NAME='cuMemsetD8_v2')
  IMPORT
  INTEGER (KIND=C_INTPTR_T), VALUE :: IPTR
  INTEGER (KIND=C_SIGNED_CHAR), VALUE :: IVAL
  INTEGER (KIND=C_SIZE_T), VALUE :: ICOUNT
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUGETERRORSTRING (IRC, CSTR) BIND (C, NAME='cuGetErrorString')
  IMPORT
  INTEGER (KIND=C_INT), VALUE :: IRC
  TYPE (C_PTR) :: CSTR
END FUNCTION

! OpenACC runtime, C API
TYPE (C_PTR) FUNCTION ACC_MALLOC_C (ISIZE) BIND (C, NAME='acc_malloc')
  IMPORT
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE
END FUNCTION

SUBROUTINE ACC_FREE_C (P) BIND (C, NAME='acc_free')
  IMPORT
  TYPE (C_PTR), VALUE :: P
END SUBROUTINE

SUBROUTINE ACC_MAP_DATA_C (H, D, ISIZE) BIND (C, NAME='acc_map_data')
  IMPORT
  TYPE (C_PTR), VALUE :: H, D
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE
END SUBROUTINE

SUBROUTINE ACC_UNMAP_DATA_C (H) BIND (C, NAME='acc_unmap_data')
  IMPORT
  TYPE (C_PTR), VALUE :: H
END SUBROUTINE

TYPE (C_PTR) FUNCTION ACC_CREATE_C (H, ISIZE) BIND (C, NAME='acc_create')
  IMPORT
  TYPE (C_PTR), VALUE :: H
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE
END FUNCTION

SUBROUTINE ACC_DELETE_C (H, ISIZE) BIND (C, NAME='acc_delete')
  IMPORT
  TYPE (C_PTR), VALUE :: H
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE
END SUBROUTINE

END INTERFACE

LOGICAL :: LLINIT = .FALSE.
INTEGER (KIND=C_INT) :: IDEV = -1        ! CUDA device of the current context

CONTAINS

SUBROUTINE GPU_INIT

TYPE (C_PTR) :: CTX

IF (LLINIT) RETURN
! Let OpenACC create its context (on the device selected by the program, if any)
CALL ACC_INIT (ACC_DEVICE_NVIDIA)
CALL CK (CUCTXGETCURRENT (CTX), 'cuCtxGetCurrent')
IF (.NOT. C_ASSOCIATED (CTX)) CALL ABOR1 ('GPU_INIT: no current CUDA context after ACC_INIT')
CALL CK (CUCTXGETDEVICE (IDEV), 'cuCtxGetDevice')
LLINIT = .TRUE.

END SUBROUTINE GPU_INIT

FUNCTION GPU_MEMORY_SIZE () RESULT (KBYTES)

INTEGER (KIND=JPIB) :: KBYTES
INTEGER (KIND=C_SIZE_T) :: IFREE, ITOTAL

CALL GPU_INIT
CALL CK (CUMEMGETINFO (IFREE, ITOTAL), 'cuMemGetInfo')
KBYTES = INT (ITOTAL, JPIB)

END FUNCTION GPU_MEMORY_SIZE

FUNCTION GPU_VMM_GRANULARITY () RESULT (KBYTES)

INTEGER (KIND=JPIB) :: KBYTES
TYPE (CUMEMALLOCATIONPROP) :: YLPROP
INTEGER (KIND=C_SIZE_T) :: IGRAN

CALL GPU_INIT
CALL SET_PROP (YLPROP)
CALL CK (CUMEMGETALLOCATIONGRANULARITY (IGRAN, YLPROP, CU_MEM_ALLOC_GRANULARITY_MINIMUM), &
       & 'cuMemGetAllocationGranularity')
KBYTES = INT (IGRAN, JPIB)

END FUNCTION GPU_VMM_GRANULARITY

FUNCTION GPU_VMM_RESERVE (KBYTES) RESULT (KDEV)

INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES
INTEGER (KIND=C_INTPTR_T) :: KDEV

CALL GPU_INIT
CALL CK (CUMEMADDRESSRESERVE (KDEV, INT (KBYTES, C_SIZE_T), 0_C_SIZE_T, 0_C_INTPTR_T, 0_C_LONG_LONG), &
       & 'cuMemAddressReserve')

END FUNCTION GPU_VMM_RESERVE

SUBROUTINE GPU_VMM_FREE (KDEV, KBYTES)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KDEV
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

CALL CK (CUMEMADDRESSFREE (KDEV, INT (KBYTES, C_SIZE_T)), 'cuMemAddressFree')

END SUBROUTINE GPU_VMM_FREE

SUBROUTINE GPU_VMM_MAP (KDEV, KBYTES)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KDEV
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

TYPE (CUMEMALLOCATIONPROP) :: YLPROP
TYPE (CUMEMACCESSDESC) :: YLDESC
INTEGER (KIND=C_LONG_LONG) :: IHANDLE

CALL SET_PROP (YLPROP)
CALL CK (CUMEMCREATE (IHANDLE, INT (KBYTES, C_SIZE_T), YLPROP, 0_C_LONG_LONG), &
       & 'cuMemCreate (out of device memory?)')
CALL CK (CUMEMMAP (KDEV, INT (KBYTES, C_SIZE_T), 0_C_SIZE_T, IHANDLE, 0_C_LONG_LONG), 'cuMemMap')
! The mapping keeps the memory alive; the handle is no longer needed
CALL CK (CUMEMRELEASE (IHANDLE), 'cuMemRelease')
YLDESC%YLOCATION%ITYPE = CU_MEM_LOCATION_TYPE_DEVICE
YLDESC%YLOCATION%ID = IDEV
YLDESC%IFLAGS = CU_MEM_ACCESS_FLAGS_PROT_READWRITE
CALL CK (CUMEMSETACCESS (KDEV, INT (KBYTES, C_SIZE_T), YLDESC, 1_C_SIZE_T), 'cuMemSetAccess')

END SUBROUTINE GPU_VMM_MAP

SUBROUTINE GPU_VMM_UNMAP (KDEV, KBYTES)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KDEV
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

CALL CK (CUCTXSYNCHRONIZE (), 'cuCtxSynchronize')
CALL CK (CUMEMUNMAP (KDEV, INT (KBYTES, C_SIZE_T)), 'cuMemUnmap')

END SUBROUTINE GPU_VMM_UNMAP

FUNCTION GPU_MALLOC (KBYTES) RESULT (KDEV)

INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES
INTEGER (KIND=C_INTPTR_T) :: KDEV

CALL GPU_INIT
KDEV = TRANSFER (ACC_MALLOC_C (INT (KBYTES, C_SIZE_T)), KDEV)
IF (KDEV == 0) CALL ABOR1 ('GPU_MALLOC: acc_malloc failed (out of device memory?)')

END FUNCTION GPU_MALLOC

SUBROUTINE GPU_FREE (KDEV)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KDEV

CALL ACC_FREE_C (TRANSFER (KDEV, C_NULL_PTR))

END SUBROUTINE GPU_FREE

SUBROUTINE GPU_MAP_DATA (KHOST, KDEV, KBYTES)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KHOST, KDEV
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

CALL ACC_MAP_DATA_C (TRANSFER (KHOST, C_NULL_PTR), TRANSFER (KDEV, C_NULL_PTR), INT (KBYTES, C_SIZE_T))

END SUBROUTINE GPU_MAP_DATA

SUBROUTINE GPU_UNMAP_DATA (KHOST)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KHOST

CALL ACC_UNMAP_DATA_C (TRANSFER (KHOST, C_NULL_PTR))

END SUBROUTINE GPU_UNMAP_DATA

FUNCTION GPU_CREATE (KHOST, KBYTES) RESULT (KDEV)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KHOST
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES
INTEGER (KIND=C_INTPTR_T) :: KDEV

CALL GPU_INIT
KDEV = TRANSFER (ACC_CREATE_C (TRANSFER (KHOST, C_NULL_PTR), INT (KBYTES, C_SIZE_T)), KDEV)

END FUNCTION GPU_CREATE

SUBROUTINE GPU_DELETE (KHOST, KDEV, KBYTES)

! KDEV is not needed by acc_delete; it is in the interface for the AMD version

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KHOST, KDEV
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

CALL ACC_DELETE_C (TRANSFER (KHOST, C_NULL_PTR), INT (KBYTES, C_SIZE_T))

END SUBROUTINE GPU_DELETE

SUBROUTINE GPU_MEMSET (KDEV, KBYTE, KBYTES)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KDEV
INTEGER, INTENT (IN) :: KBYTE
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

CALL CK (CUCTXSYNCHRONIZE (), 'cuCtxSynchronize')
CALL CK (CUMEMSETD8 (KDEV, INT (MERGE (KBYTE - 256, KBYTE, KBYTE > 127), C_SIGNED_CHAR), &
       & INT (KBYTES, C_SIZE_T)), 'cuMemsetD8')
CALL CK (CUCTXSYNCHRONIZE (), 'cuCtxSynchronize')

END SUBROUTINE GPU_MEMSET

SUBROUTINE SET_PROP (YDPROP)

! Pinned device memory on the current device, usable by GPUDirect RDMA (CUDA-aware MPI)

TYPE (CUMEMALLOCATIONPROP), INTENT (OUT) :: YDPROP

YDPROP%ITYPE = CU_MEM_ALLOCATION_TYPE_PINNED
YDPROP%IREQUESTEDHANDLETYPES = 0
YDPROP%YLOCATION%ITYPE = CU_MEM_LOCATION_TYPE_DEVICE
YDPROP%YLOCATION%ID = IDEV
YDPROP%WIN32HANDLEMETADATA = C_NULL_PTR
YDPROP%IALLOCFLAGS = ALLOCFLAGS_GPUDIRECTRDMACAPABLE

END SUBROUTINE SET_PROP

SUBROUTINE CK (KRC, CDWHAT)

! Abort with the CUDA error message if a driver call failed

INTEGER (KIND=C_INT), INTENT (IN) :: KRC
CHARACTER (LEN=*), INTENT (IN) :: CDWHAT

TYPE (C_PTR) :: CSTR
CHARACTER (KIND=C_CHAR), POINTER :: CLCH (:)
CHARACTER (LEN=128) :: CLMESS
CHARACTER (LEN=256) :: CLTEXT
INTEGER :: J

IF (KRC == 0) RETURN
CLMESS = ''
IF (CUGETERRORSTRING (KRC, CSTR) == 0 .AND. C_ASSOCIATED (CSTR)) THEN
  CALL C_F_POINTER (CSTR, CLCH, [LEN (CLMESS)])
  DO J = 1, LEN (CLMESS)
    IF (CLCH (J) == C_NULL_CHAR) EXIT
    CLMESS (J:J) = CLCH (J)
  ENDDO
ENDIF
WRITE (CLTEXT, '(A,A,I0,A,A)') CDWHAT, ' failed: CUDA error ', KRC, ', ', TRIM (CLMESS)
CALL ABOR1 (TRIM (CLTEXT))

END SUBROUTINE CK

END MODULE GPU_HELPERS_MOD

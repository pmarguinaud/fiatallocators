MODULE GPU_HELPERS_MOD

! GPU helper set, NVIDIA version: CUDA driver API (VMM) and OpenACC runtime (C API), through
! BIND (C) interfaces. The GPU classes call only these routines, so that the AMD version
! (HIP + OpenMP) is a module with the same name and the same public routines.
! Addresses (host and device) are INTEGER (KIND=C_INTPTR_T).
!
!   GPU_INIT                         initialise the offload runtime, find the device
!   GPU_MEMORY_SIZE ()               device memory, bytes
!   GPU_VMM_GRANULARITY ()           VMM allocation granularity, bytes
!   GPU_VMM_RESERVE (KBYTES)         reserve a range of device addresses (no memory)
!   GPU_VMM_FREE (KDEV, KBYTES)      free the range
!   GPU_VMM_MAP (KDEV, KBYTES)       create KBYTES of physical memory (GPUDirect RDMA capable) and
!                                    map it at KDEV, read/write
!   GPU_VMM_UNMAP (KDEV, KBYTES)     unmap (the memory is released with its last mapping)
!   GPU_MALLOC (KBYTES), GPU_FREE (KDEV)       plain device memory (acc_malloc / acc_free)
!   GPU_MAP_DATA (KHOST, KDEV, KBYTES)         declare host range -> device range (acc_map_data)
!   GPU_UNMAP_DATA (KHOST)                     (acc_unmap_data)
!   KDEV = GPU_CREATE (KHOST, KBYTES)          device copy of a host array (acc_create); returns
!                                              its address
!   GPU_DELETE (KHOST, KDEV, KBYTES)           (acc_delete)
!   GPU_MEMSET (KDEV, KBYTE, KBYTES)           fill device memory, synchronous

USE ISO_C_BINDING
USE PARKIND1, ONLY : JPIB
USE OPENACC, ONLY : ACC_INIT, ACC_DEVICE_NVIDIA

IMPLICIT NONE

PRIVATE
PUBLIC :: GPU_INIT, GPU_MEMORY_SIZE, GPU_VMM_GRANULARITY, GPU_VMM_RESERVE, GPU_VMM_FREE
PUBLIC :: GPU_VMM_MAP, GPU_VMM_UNMAP, GPU_MALLOC, GPU_FREE, GPU_MAP_DATA, GPU_UNMAP_DATA
PUBLIC :: GPU_CREATE, GPU_DELETE, GPU_MEMSET

#include "abor1.intfb.h"

! CUDA driver API structures and constants (cuda.h)
TYPE, BIND (C) :: CUMEMLOCATION
  INTEGER (KIND=C_INT) :: ITYPE
  INTEGER (KIND=C_INT) :: ID
END TYPE

TYPE, BIND (C) :: CUMEMALLOCATIONPROP
  INTEGER (KIND=C_INT) :: ITYPE
  INTEGER (KIND=C_INT) :: IREQUESTEDHANDLETYPES
  TYPE (CUMEMLOCATION) :: YLOCATION
  TYPE (C_PTR) :: WIN32HANDLEMETADATA
  INTEGER (KIND=C_INT64_T) :: IALLOCFLAGS   ! compressionType, gpuDirectRDMACapable, usage, reserved
END TYPE

TYPE, BIND (C) :: CUMEMACCESSDESC
  TYPE (CUMEMLOCATION) :: YLOCATION
  INTEGER (KIND=C_INT) :: IFLAGS
END TYPE

INTEGER (KIND=C_INT), PARAMETER :: CU_MEM_ALLOCATION_TYPE_PINNED = 1
INTEGER (KIND=C_INT), PARAMETER :: CU_MEM_LOCATION_TYPE_DEVICE = 1
INTEGER (KIND=C_INT), PARAMETER :: CU_MEM_ACCESS_FLAGS_PROT_READWRITE = 3
INTEGER (KIND=C_INT), PARAMETER :: CU_MEM_ALLOC_GRANULARITY_MINIMUM = 0
INTEGER (KIND=C_INT64_T), PARAMETER :: ALLOCFLAGS_GPUDIRECTRDMACAPABLE = 256   ! byte 1 of allocFlags

INTERFACE

INTEGER (KIND=C_INT) FUNCTION CUCTXGETCURRENT (CTX) BIND (C, NAME='cuCtxGetCurrent')
  IMPORT
  TYPE (C_PTR) :: CTX
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUCTXGETDEVICE (IDEV) BIND (C, NAME='cuCtxGetDevice')
  IMPORT
  INTEGER (KIND=C_INT) :: IDEV
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUCTXSYNCHRONIZE () BIND (C, NAME='cuCtxSynchronize')
  IMPORT
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUMEMGETINFO (IFREE, ITOTAL) BIND (C, NAME='cuMemGetInfo_v2')
  IMPORT
  INTEGER (KIND=C_SIZE_T) :: IFREE, ITOTAL
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUMEMGETALLOCATIONGRANULARITY (IGRAN, YPROP, IOPTION) &
                            & BIND (C, NAME='cuMemGetAllocationGranularity')
  IMPORT
  INTEGER (KIND=C_SIZE_T) :: IGRAN
  TYPE (CUMEMALLOCATIONPROP) :: YPROP
  INTEGER (KIND=C_INT), VALUE :: IOPTION
END FUNCTION


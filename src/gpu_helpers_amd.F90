MODULE GPU_HELPERS_MOD

! GPU helper set, AMD version: HIP (VMM API) and the OpenMP offload runtime (C API), through
! BIND (C) interfaces. Same module name and public routines as gpu_helpers_nvidia.F90.
! Addresses (host and device) are INTEGER (KIND=C_INTPTR_T).
!
!   GPU_INIT                         find the OpenMP default device, make it the HIP device
!   GPU_MEMORY_SIZE ()               device memory, bytes
!   GPU_VMM_GRANULARITY ()           VMM allocation granularity, bytes
!   GPU_VMM_RESERVE (KBYTES)         reserve a range of device addresses (no memory)
!   GPU_VMM_FREE (KDEV, KBYTES)      free the range
!   GPU_VMM_MAP (KDEV, KBYTES)       create KBYTES of physical memory (GPUDirect RDMA capable) and
!                                    map it at KDEV, read/write
!   GPU_VMM_UNMAP (KDEV, KBYTES)     unmap (the memory is released with its last mapping)
!   GPU_MALLOC (KBYTES), GPU_FREE (KDEV)       plain device memory (omp_target_alloc / free)
!   GPU_MAP_DATA (KHOST, KDEV, KBYTES)         declare host range -> device range
!                                              (omp_target_associate_ptr)
!   GPU_UNMAP_DATA (KHOST)                     (omp_target_disassociate_ptr)
!   KDEV = GPU_CREATE (KHOST, KBYTES)          device copy of a host array: omp_target_alloc +
!                                              omp_target_associate_ptr; returns its address
!   GPU_DELETE (KHOST, KDEV, KBYTES)           disassociate + omp_target_free
!   GPU_MEMSET (KDEV, KBYTE, KBYTES)           fill device memory, synchronous
!
! The OpenMP device number and the HIP device id are taken to be the same (both enumerate the
! GPUs visible to the process, in the same order).

USE ISO_C_BINDING
USE PARKIND1, ONLY : JPIB

IMPLICIT NONE

PRIVATE
PUBLIC :: GPU_INIT, GPU_MEMORY_SIZE, GPU_VMM_GRANULARITY, GPU_VMM_RESERVE, GPU_VMM_FREE
PUBLIC :: GPU_VMM_MAP, GPU_VMM_UNMAP, GPU_MALLOC, GPU_FREE, GPU_MAP_DATA, GPU_UNMAP_DATA
PUBLIC :: GPU_CREATE, GPU_DELETE, GPU_MEMSET

#include "abor1.intfb.h"

! HIP structures and constants (hip/hip_runtime_api.h, ROCm 7). Layout checked by
! tests/c/hip_vmm_layout.c: hipMemAllocationProp is 32 bytes, allocFlags is 4 bytes at offset 24
! (compressionType, gpuDirectRDMACapable: 1 byte each; usage: 2 bytes), followed by 4 bytes of
! padding.
TYPE, BIND (C) :: HIPMEMLOCATION
  INTEGER (KIND=C_INT) :: ITYPE
  INTEGER (KIND=C_INT) :: ID
END TYPE

TYPE, BIND (C) :: HIPMEMALLOCATIONPROP
  INTEGER (KIND=C_INT) :: ITYPE
  INTEGER (KIND=C_INT) :: IREQUESTEDHANDLETYPE
  TYPE (HIPMEMLOCATION) :: YLOCATION
  TYPE (C_PTR) :: WIN32HANDLEMETADATA
  INTEGER (KIND=C_SIGNED_CHAR) :: ICOMPRESSIONTYPE
  INTEGER (KIND=C_SIGNED_CHAR) :: IGPUDIRECTRDMACAPABLE
  INTEGER (KIND=C_SHORT) :: IUSAGE
END TYPE

TYPE, BIND (C) :: HIPMEMACCESSDESC
  TYPE (HIPMEMLOCATION) :: YLOCATION
  INTEGER (KIND=C_INT) :: IFLAGS
END TYPE

INTEGER (KIND=C_INT), PARAMETER :: HIP_MEM_ALLOCATION_TYPE_PINNED = 1
INTEGER (KIND=C_INT), PARAMETER :: HIP_MEM_LOCATION_TYPE_DEVICE = 1
INTEGER (KIND=C_INT), PARAMETER :: HIP_MEM_ACCESS_FLAGS_PROT_READWRITE = 3
INTEGER (KIND=C_INT), PARAMETER :: HIP_MEM_ALLOC_GRANULARITY_MINIMUM = 0
INTEGER (KIND=C_INT), PARAMETER :: HIP_DEVICE_ATTRIBUTE_VMM_SUPPORTED = 89

INTERFACE

INTEGER (KIND=C_INT) FUNCTION HIPSETDEVICE (IDEV) BIND (C, NAME='hipSetDevice')
  IMPORT
  INTEGER (KIND=C_INT), VALUE :: IDEV
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPDEVICEGETATTRIBUTE (IVAL, IATTR, IDEV) BIND (C, NAME='hipDeviceGetAttribute')
  IMPORT
  INTEGER (KIND=C_INT) :: IVAL
  INTEGER (KIND=C_INT), VALUE :: IATTR, IDEV
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPDEVICESYNCHRONIZE () BIND (C, NAME='hipDeviceSynchronize')
  IMPORT
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPMEMGETINFO (IFREE, ITOTAL) BIND (C, NAME='hipMemGetInfo')
  IMPORT
  INTEGER (KIND=C_SIZE_T) :: IFREE, ITOTAL
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPMEMGETALLOCATIONGRANULARITY (IGRAN, YPROP, IOPTION) &
                            & BIND (C, NAME='hipMemGetAllocationGranularity')
  IMPORT
  INTEGER (KIND=C_SIZE_T) :: IGRAN
  TYPE (HIPMEMALLOCATIONPROP) :: YPROP
  INTEGER (KIND=C_INT), VALUE :: IOPTION
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPMEMADDRESSRESERVE (IPTR, ISIZE, IALIGN, IADDR, IFLAGS) &
                            & BIND (C, NAME='hipMemAddressReserve')
  IMPORT
  INTEGER (KIND=C_INTPTR_T) :: IPTR
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE, IALIGN
  INTEGER (KIND=C_INTPTR_T), VALUE :: IADDR
  INTEGER (KIND=C_LONG_LONG), VALUE :: IFLAGS
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPMEMADDRESSFREE (IPTR, ISIZE) BIND (C, NAME='hipMemAddressFree')
  IMPORT
  INTEGER (KIND=C_INTPTR_T), VALUE :: IPTR
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPMEMCREATE (IHANDLE, ISIZE, YPROP, IFLAGS) BIND (C, NAME='hipMemCreate')
  IMPORT
  INTEGER (KIND=C_INTPTR_T) :: IHANDLE
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE
  TYPE (HIPMEMALLOCATIONPROP) :: YPROP
  INTEGER (KIND=C_LONG_LONG), VALUE :: IFLAGS
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPMEMMAP (IPTR, ISIZE, IOFFSET, IHANDLE, IFLAGS) BIND (C, NAME='hipMemMap')
  IMPORT
  INTEGER (KIND=C_INTPTR_T), VALUE :: IPTR
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE, IOFFSET
  INTEGER (KIND=C_INTPTR_T), VALUE :: IHANDLE
  INTEGER (KIND=C_LONG_LONG), VALUE :: IFLAGS
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPMEMRELEASE (IHANDLE) BIND (C, NAME='hipMemRelease')
  IMPORT
  INTEGER (KIND=C_INTPTR_T), VALUE :: IHANDLE
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPMEMSETACCESS (IPTR, ISIZE, YDESC, ICOUNT) BIND (C, NAME='hipMemSetAccess')
  IMPORT
  INTEGER (KIND=C_INTPTR_T), VALUE :: IPTR
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE
  TYPE (HIPMEMACCESSDESC) :: YDESC
  INTEGER (KIND=C_SIZE_T), VALUE :: ICOUNT
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPMEMUNMAP (IPTR, ISIZE) BIND (C, NAME='hipMemUnmap')
  IMPORT
  INTEGER (KIND=C_INTPTR_T), VALUE :: IPTR
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPMEMSETD8 (IPTR, IVAL, ICOUNT) BIND (C, NAME='hipMemsetD8')
  IMPORT
  INTEGER (KIND=C_INTPTR_T), VALUE :: IPTR
  INTEGER (KIND=C_SIGNED_CHAR), VALUE :: IVAL
  INTEGER (KIND=C_SIZE_T), VALUE :: ICOUNT
END FUNCTION

TYPE (C_PTR) FUNCTION HIPGETERRORSTRING (IRC) BIND (C, NAME='hipGetErrorString')
  IMPORT
  INTEGER (KIND=C_INT), VALUE :: IRC
END FUNCTION

! OpenMP offload runtime, C API
INTEGER (KIND=C_INT) FUNCTION OMP_GET_DEFAULT_DEVICE_C () BIND (C, NAME='omp_get_default_device')
  IMPORT
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION OMP_GET_NUM_DEVICES_C () BIND (C, NAME='omp_get_num_devices')
  IMPORT
END FUNCTION

TYPE (C_PTR) FUNCTION OMP_TARGET_ALLOC_C (ISIZE, IDEV) BIND (C, NAME='omp_target_alloc')
  IMPORT
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE
  INTEGER (KIND=C_INT), VALUE :: IDEV
END FUNCTION

SUBROUTINE OMP_TARGET_FREE_C (P, IDEV) BIND (C, NAME='omp_target_free')
  IMPORT
  TYPE (C_PTR), VALUE :: P
  INTEGER (KIND=C_INT), VALUE :: IDEV
END SUBROUTINE

INTEGER (KIND=C_INT) FUNCTION OMP_TARGET_ASSOCIATE_PTR_C (H, D, ISIZE, IOFFSET, IDEV) &
                            & BIND (C, NAME='omp_target_associate_ptr')
  IMPORT
  TYPE (C_PTR), VALUE :: H, D
  INTEGER (KIND=C_SIZE_T), VALUE :: ISIZE, IOFFSET
  INTEGER (KIND=C_INT), VALUE :: IDEV
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION OMP_TARGET_DISASSOCIATE_PTR_C (H, IDEV) &
                            & BIND (C, NAME='omp_target_disassociate_ptr')
  IMPORT
  TYPE (C_PTR), VALUE :: H
  INTEGER (KIND=C_INT), VALUE :: IDEV
END FUNCTION

END INTERFACE

LOGICAL :: LLINIT = .FALSE.
INTEGER (KIND=C_INT) :: IDEV = -1        ! OpenMP default device = HIP device

CONTAINS

SUBROUTINE GPU_INIT

INTEGER (KIND=C_INT) :: IVMM
CHARACTER (LEN=128) :: CLMESS

IF (LLINIT) RETURN
IF (OMP_GET_NUM_DEVICES_C () < 1) CALL ABOR1 ('GPU_INIT: no OpenMP offload device')
! The device selected by the program (omp_set_default_device), if any
IDEV = OMP_GET_DEFAULT_DEVICE_C ()
CALL CK (HIPSETDEVICE (IDEV), 'hipSetDevice')
CALL CK (HIPDEVICEGETATTRIBUTE (IVMM, HIP_DEVICE_ATTRIBUTE_VMM_SUPPORTED, IDEV), &
       & 'hipDeviceGetAttribute (VirtualMemoryManagementSupported)')
IF (IVMM /= 1) THEN
  WRITE (CLMESS, '(A,I0,A)') 'GPU_INIT: device ', IDEV, ' does not support HIP virtual memory management'
  CALL ABOR1 (TRIM (CLMESS))
ENDIF
LLINIT = .TRUE.

END SUBROUTINE GPU_INIT

FUNCTION GPU_MEMORY_SIZE () RESULT (KBYTES)

INTEGER (KIND=JPIB) :: KBYTES
INTEGER (KIND=C_SIZE_T) :: IFREE, ITOTAL

CALL GPU_INIT
CALL CK (HIPMEMGETINFO (IFREE, ITOTAL), 'hipMemGetInfo')
KBYTES = INT (ITOTAL, JPIB)

END FUNCTION GPU_MEMORY_SIZE

FUNCTION GPU_VMM_GRANULARITY () RESULT (KBYTES)

INTEGER (KIND=JPIB) :: KBYTES
TYPE (HIPMEMALLOCATIONPROP) :: YLPROP
INTEGER (KIND=C_SIZE_T) :: IGRAN

CALL GPU_INIT
CALL SET_PROP (YLPROP)
CALL CK (HIPMEMGETALLOCATIONGRANULARITY (IGRAN, YLPROP, HIP_MEM_ALLOC_GRANULARITY_MINIMUM), &
       & 'hipMemGetAllocationGranularity')
KBYTES = INT (IGRAN, JPIB)

END FUNCTION GPU_VMM_GRANULARITY

FUNCTION GPU_VMM_RESERVE (KBYTES) RESULT (KDEV)

INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES
INTEGER (KIND=C_INTPTR_T) :: KDEV

CALL GPU_INIT
CALL CK (HIPMEMADDRESSRESERVE (KDEV, INT (KBYTES, C_SIZE_T), 0_C_SIZE_T, 0_C_INTPTR_T, 0_C_LONG_LONG), &
       & 'hipMemAddressReserve')

END FUNCTION GPU_VMM_RESERVE

SUBROUTINE GPU_VMM_FREE (KDEV, KBYTES)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KDEV
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

CALL CK (HIPMEMADDRESSFREE (KDEV, INT (KBYTES, C_SIZE_T)), 'hipMemAddressFree')

END SUBROUTINE GPU_VMM_FREE

SUBROUTINE GPU_VMM_MAP (KDEV, KBYTES)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KDEV
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

TYPE (HIPMEMALLOCATIONPROP) :: YLPROP
TYPE (HIPMEMACCESSDESC) :: YLDESC
INTEGER (KIND=C_INTPTR_T) :: IHANDLE

CALL SET_PROP (YLPROP)
CALL CK (HIPMEMCREATE (IHANDLE, INT (KBYTES, C_SIZE_T), YLPROP, 0_C_LONG_LONG), &
       & 'hipMemCreate (out of device memory?)')
CALL CK (HIPMEMMAP (KDEV, INT (KBYTES, C_SIZE_T), 0_C_SIZE_T, IHANDLE, 0_C_LONG_LONG), 'hipMemMap')
! The mapping keeps the memory alive; the handle is no longer needed
CALL CK (HIPMEMRELEASE (IHANDLE), 'hipMemRelease')
YLDESC%YLOCATION%ITYPE = HIP_MEM_LOCATION_TYPE_DEVICE
YLDESC%YLOCATION%ID = IDEV
YLDESC%IFLAGS = HIP_MEM_ACCESS_FLAGS_PROT_READWRITE
CALL CK (HIPMEMSETACCESS (KDEV, INT (KBYTES, C_SIZE_T), YLDESC, 1_C_SIZE_T), 'hipMemSetAccess')

END SUBROUTINE GPU_VMM_MAP

SUBROUTINE GPU_VMM_UNMAP (KDEV, KBYTES)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KDEV
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

CALL CK (HIPDEVICESYNCHRONIZE (), 'hipDeviceSynchronize')
CALL CK (HIPMEMUNMAP (KDEV, INT (KBYTES, C_SIZE_T)), 'hipMemUnmap')

END SUBROUTINE GPU_VMM_UNMAP

FUNCTION GPU_MALLOC (KBYTES) RESULT (KDEV)

INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES
INTEGER (KIND=C_INTPTR_T) :: KDEV

CALL GPU_INIT
KDEV = TRANSFER (OMP_TARGET_ALLOC_C (INT (KBYTES, C_SIZE_T), IDEV), KDEV)
IF (KDEV == 0) CALL ABOR1 ('GPU_MALLOC: omp_target_alloc failed (out of device memory?)')

END FUNCTION GPU_MALLOC

SUBROUTINE GPU_FREE (KDEV)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KDEV

CALL OMP_TARGET_FREE_C (TRANSFER (KDEV, C_NULL_PTR), IDEV)

END SUBROUTINE GPU_FREE

SUBROUTINE GPU_MAP_DATA (KHOST, KDEV, KBYTES)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KHOST, KDEV
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

IF (OMP_TARGET_ASSOCIATE_PTR_C (TRANSFER (KHOST, C_NULL_PTR), TRANSFER (KDEV, C_NULL_PTR), &
  & INT (KBYTES, C_SIZE_T), 0_C_SIZE_T, IDEV) /= 0) CALL ABOR1 ('GPU_MAP_DATA: omp_target_associate_ptr failed')

END SUBROUTINE GPU_MAP_DATA

SUBROUTINE GPU_UNMAP_DATA (KHOST)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KHOST

IF (OMP_TARGET_DISASSOCIATE_PTR_C (TRANSFER (KHOST, C_NULL_PTR), IDEV) /= 0) &
  & CALL ABOR1 ('GPU_UNMAP_DATA: omp_target_disassociate_ptr failed')

END SUBROUTINE GPU_UNMAP_DATA

FUNCTION GPU_CREATE (KHOST, KBYTES) RESULT (KDEV)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KHOST
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES
INTEGER (KIND=C_INTPTR_T) :: KDEV

KDEV = GPU_MALLOC (KBYTES)
CALL GPU_MAP_DATA (KHOST, KDEV, KBYTES)

END FUNCTION GPU_CREATE

SUBROUTINE GPU_DELETE (KHOST, KDEV, KBYTES)

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KHOST, KDEV
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

CALL GPU_UNMAP_DATA (KHOST)
CALL GPU_FREE (KDEV)

END SUBROUTINE GPU_DELETE

SUBROUTINE GPU_MEMSET (KDEV, KBYTE, KBYTES)

! OpenMP target regions without NOWAIT are complete when they return, so only the HIP work
! needs to be waited for

INTEGER (KIND=C_INTPTR_T), INTENT (IN) :: KDEV
INTEGER, INTENT (IN) :: KBYTE
INTEGER (KIND=JPIB), INTENT (IN) :: KBYTES

CALL CK (HIPDEVICESYNCHRONIZE (), 'hipDeviceSynchronize')
CALL CK (HIPMEMSETD8 (KDEV, INT (MERGE (KBYTE - 256, KBYTE, KBYTE > 127), C_SIGNED_CHAR), &
       & INT (KBYTES, C_SIZE_T)), 'hipMemsetD8')
CALL CK (HIPDEVICESYNCHRONIZE (), 'hipDeviceSynchronize')

END SUBROUTINE GPU_MEMSET

SUBROUTINE SET_PROP (YDPROP)

! Pinned device memory on the current device, usable by GPUDirect RDMA (GPU-aware MPI)

TYPE (HIPMEMALLOCATIONPROP), INTENT (OUT) :: YDPROP

YDPROP%ITYPE = HIP_MEM_ALLOCATION_TYPE_PINNED
YDPROP%IREQUESTEDHANDLETYPE = 0
YDPROP%YLOCATION%ITYPE = HIP_MEM_LOCATION_TYPE_DEVICE
YDPROP%YLOCATION%ID = IDEV
YDPROP%WIN32HANDLEMETADATA = C_NULL_PTR
YDPROP%ICOMPRESSIONTYPE = 0
YDPROP%IGPUDIRECTRDMACAPABLE = 1
YDPROP%IUSAGE = 0

END SUBROUTINE SET_PROP

SUBROUTINE CK (KRC, CDWHAT)

! Abort with the HIP error message if a HIP call failed

INTEGER (KIND=C_INT), INTENT (IN) :: KRC
CHARACTER (LEN=*), INTENT (IN) :: CDWHAT

CHARACTER (KIND=C_CHAR), POINTER :: CLCH (:)
CHARACTER (LEN=128) :: CLMESS
CHARACTER (LEN=256) :: CLTEXT
INTEGER :: J

IF (KRC == 0) RETURN
CLMESS = ''
CALL C_F_POINTER (HIPGETERRORSTRING (KRC), CLCH, [LEN (CLMESS)])
DO J = 1, LEN (CLMESS)
  IF (CLCH (J) == C_NULL_CHAR) EXIT
  CLMESS (J:J) = CLCH (J)
ENDDO
WRITE (CLTEXT, '(A,A,I0,A,A)') CDWHAT, ' failed: HIP error ', KRC, ', ', TRIM (CLMESS)
CALL ABOR1 (TRIM (CLTEXT))

END SUBROUTINE CK

END MODULE GPU_HELPERS_MOD

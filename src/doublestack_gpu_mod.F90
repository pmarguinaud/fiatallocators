MODULE DOUBLESTACK_GPU_MOD

! DOUBLESTACK_GPU: double stack on a range of device virtual addresses (CUDA VMM on NVIDIA; HIP
! on AMD later, through the same GPU_HELPERS_MOD interface).
!
! INIT reserves KSIZE bytes of device addresses (0 = device memory size), rounded down to a
! multiple of VMM_CHUNK; this uses no memory. Physical memory is mapped VMM_CHUNK bytes at a time
! as each side grows: the lower side from the start of the range, the upper side from its end.
! Chunks stay mapped when arrays are freed ("keep" policy), so addresses never change and memory
! is mapped only up to the high-water mark of each side. DESTROY unmaps everything.
!
! The arrays are host pointers into a host mirror of the range (virtual memory, not touched unless
! the program copies data to the host), declared once to the offload runtime (acc_map_data), so
! that PRESENT (X), UPDATE and HOST_DATA USE_DEVICE work on every array of the stack.

USE ISO_C_BINDING
USE ISO_FORTRAN_ENV, ONLY : OUTPUT_UNIT
USE PARKIND1, ONLY : JPIB
USE ALLOCATOR_PARAMS_MOD, ONLY : VMM_CHUNK, DEBUG_FILL_BYTE
USE STACK_CORE_MOD, ONLY : STACK_BASE, MIB
USE HOST_HELPERS_MOD, ONLY : HOST_RESERVE, HOST_RELEASE
USE GPU_HELPERS_MOD, ONLY : GPU_INIT, GPU_MEMORY_SIZE, GPU_VMM_GRANULARITY, GPU_VMM_RESERVE, &
                          & GPU_VMM_FREE, GPU_VMM_MAP, GPU_VMM_UNMAP, GPU_MAP_DATA, GPU_UNMAP_DATA, &
                          & GPU_MEMSET

IMPLICIT NONE

PRIVATE
PUBLIC :: DOUBLESTACK_GPU

#include "abor1.intfb.h"

TYPE, EXTENDS (STACK_BASE) :: DOUBLESTACK_GPU
  INTEGER (KIND=C_INTPTR_T) :: IDEV = 0       ! device address of the reserved range
  INTEGER (KIND=JPIB) :: IMAPLOW = 0          ! bytes mapped from the start of the range
  INTEGER (KIND=JPIB) :: IMAPUP = 0           ! bytes mapped from the end of the range
CONTAINS
  PROCEDURE :: INIT => DSG_INIT
  PROCEDURE :: DESTROY => DSG_DESTROY
  PROCEDURE :: ENSURE => DSG_ENSURE
  PROCEDURE :: FILL => DSG_FILL
  PROCEDURE :: REPORT_EXTRA => DSG_REPORT_EXTRA
  FINAL :: DSG_FINAL
END TYPE DOUBLESTACK_GPU

CONTAINS

SUBROUTINE DSG_INIT (SELF, KSIZE, LDDEBUG, LDVERBOSE)

CLASS (DOUBLESTACK_GPU), INTENT (INOUT) :: SELF
INTEGER (KIND=JPIB), INTENT (IN) :: KSIZE
LOGICAL, INTENT (IN), OPTIONAL :: LDDEBUG, LDVERBOSE

INTEGER (KIND=JPIB) :: ISIZE, IGRAN
INTEGER (KIND=C_INTPTR_T) :: IHOST

CALL SELF%SET_OPTIONS ('DOUBLESTACK_GPU', LDDEBUG, LDVERBOSE)
CALL GPU_INIT
IGRAN = GPU_VMM_GRANULARITY ()
IF (MOD (VMM_CHUNK, IGRAN) /= 0) CALL ABOR1 ('DOUBLESTACK_GPU%INIT: VMM_CHUNK is not a multiple of &
  &the VMM granularity of the device')
ISIZE = KSIZE
IF (ISIZE == 0) ISIZE = GPU_MEMORY_SIZE ()
ISIZE = ISIZE / VMM_CHUNK * VMM_CHUNK
IF (ISIZE < VMM_CHUNK) CALL ABOR1 ('DOUBLESTACK_GPU%INIT: KSIZE smaller than VMM_CHUNK')

SELF%IDEV = GPU_VMM_RESERVE (ISIZE)
IHOST = HOST_RESERVE (ISIZE)
CALL GPU_MAP_DATA (IHOST, SELF%IDEV, ISIZE)
SELF%IMAPLOW = 0
SELF%IMAPUP = 0
CALL SELF%STACK_OPEN (IHOST, ISIZE)

IF (SELF%LVERBOSE) WRITE (OUTPUT_UNIT, '(A,F0.1,A,Z0,A,Z0,A,F0.1,A,F0.1,A)') 'DOUBLESTACK_GPU%INIT: reserved ', &
  & MIB (ISIZE), ' MiB of device addresses at 0x', SELF%IDEV, ' (host mirror 0x', IHOST, '); chunk ', &
  & MIB (VMM_CHUNK), ' MiB, granularity ', MIB (IGRAN), ' MiB'

END SUBROUTINE DSG_INIT

SUBROUTINE DSG_ENSURE (SELF, KLOW, KUP)

! Map chunks so that [0, KLOW) and [KUP, SIZE) are backed by memory. A chunk already mapped by
! the other side is not mapped twice.

CLASS (DOUBLESTACK_GPU), INTENT (INOUT) :: SELF
INTEGER (KIND=JPIB), INTENT (IN) :: KLOW, KUP

DO WHILE (SELF%IMAPLOW < KLOW .AND. SELF%IMAPLOW < SELF%ISIZE - SELF%IMAPUP)
  CALL MAP_CHUNK (SELF, SELF%IMAPLOW, 'lower')
  SELF%IMAPLOW = SELF%IMAPLOW + VMM_CHUNK
ENDDO
DO WHILE (SELF%ISIZE - SELF%IMAPUP > KUP .AND. SELF%ISIZE - SELF%IMAPUP > SELF%IMAPLOW)
  CALL MAP_CHUNK (SELF, SELF%ISIZE - SELF%IMAPUP - VMM_CHUNK, 'upper')
  SELF%IMAPUP = SELF%IMAPUP + VMM_CHUNK
ENDDO

END SUBROUTINE DSG_ENSURE

SUBROUTINE MAP_CHUNK (SELF, KOFF, CDSIDE)

CLASS (DOUBLESTACK_GPU), INTENT (INOUT) :: SELF
INTEGER (KIND=JPIB), INTENT (IN) :: KOFF
CHARACTER (LEN=*), INTENT (IN) :: CDSIDE

CALL GPU_VMM_MAP (SELF%IDEV + INT (KOFF, C_INTPTR_T), VMM_CHUNK)
IF (SELF%LVERBOSE) WRITE (OUTPUT_UNIT, '(A,F0.1,A,A,A,F0.1,A,Z0,A,Z0,A)') 'DOUBLESTACK_GPU: mapped ', &
  & MIB (VMM_CHUNK), ' MiB (', CDSIDE, ' side) at offset ', MIB (KOFF), ' MiB (device 0x', &
  & SELF%IDEV + INT (KOFF, C_INTPTR_T), ' to 0x', SELF%IDEV + INT (KOFF + VMM_CHUNK - 1, C_INTPTR_T), ')'

END SUBROUTINE MAP_CHUNK

SUBROUTINE DSG_FILL (SELF, KOFF, KBYTES)

CLASS (DOUBLESTACK_GPU), INTENT (INOUT) :: SELF
INTEGER (KIND=JPIB), INTENT (IN) :: KOFF, KBYTES

CALL GPU_MEMSET (SELF%IDEV + INT (KOFF, C_INTPTR_T), DEBUG_FILL_BYTE, KBYTES)

END SUBROUTINE DSG_FILL

FUNCTION DSG_REPORT_EXTRA (SELF) RESULT (CDTEXT)

CLASS (DOUBLESTACK_GPU), INTENT (IN) :: SELF
CHARACTER (LEN=:), ALLOCATABLE :: CDTEXT

CHARACTER (LEN=128) :: CLTEXT

WRITE (CLTEXT, '(A,F0.1,A,F0.1,A,F0.1,A)') '; device memory mapped: lower ', MIB (SELF%IMAPLOW), &
  & ' MiB, upper ', MIB (SELF%IMAPUP), ' MiB, total ', MIB (SELF%IMAPLOW + SELF%IMAPUP), ' MiB'
CDTEXT = TRIM (CLTEXT)

END FUNCTION DSG_REPORT_EXTRA

SUBROUTINE DSG_DESTROY (SELF)

CLASS (DOUBLESTACK_GPU), INTENT (INOUT) :: SELF

INTEGER (KIND=JPIB) :: IOFF

IF (.NOT. SELF%LINIT) RETURN
CALL SELF%STACK_CLOSE
CALL GPU_UNMAP_DATA (SELF%IHOST)
! One unmap per chunk, as each chunk was mapped by its own call
DO IOFF = 0, SELF%IMAPLOW - VMM_CHUNK, VMM_CHUNK
  CALL GPU_VMM_UNMAP (SELF%IDEV + INT (IOFF, C_INTPTR_T), VMM_CHUNK)
ENDDO
DO IOFF = SELF%ISIZE - SELF%IMAPUP, SELF%ISIZE - VMM_CHUNK, VMM_CHUNK
  CALL GPU_VMM_UNMAP (SELF%IDEV + INT (IOFF, C_INTPTR_T), VMM_CHUNK)
ENDDO
CALL GPU_VMM_FREE (SELF%IDEV, SELF%ISIZE)
CALL HOST_RELEASE (SELF%IHOST, SELF%ISIZE)
SELF%IMAPLOW = 0
SELF%IMAPUP = 0

END SUBROUTINE DSG_DESTROY

SUBROUTINE DSG_FINAL (SELF)

TYPE (DOUBLESTACK_GPU), INTENT (INOUT) :: SELF

IF (SELF%LINIT) CALL SELF%DESTROY

END SUBROUTINE DSG_FINAL

END MODULE DOUBLESTACK_GPU_MOD

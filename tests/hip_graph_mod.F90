MODULE HIP_GRAPH_MOD

! Minimal HIP graph interface for the tests (AMD). Kernels generated from OpenMP target regions
! cannot be captured into HIP graphs (the OpenMP runtime launches them on HSA queues, not on HIP
! streams), so the graph holds hipBLAS SGEMMs, as ecTrans does on AMD (and stackdemo).
!
!   CALL GRAPH_BEGIN                 create a HIP stream and a hipBLAS handle on it, start the
!                                    capture (global mode, as in ecTrans)
!   CALL GRAPH_ADD_ONE (X, U, V)     record X = X + 1 as one SGEMM, X (M, N) += U (M, K) * V (K, N),
!                                    on device addresses; U and V set by GRAPH_ONES
!   CALL GRAPH_END (KNODES)          end the capture, instantiate; KNODES: number of nodes captured
!   CALL GRAPH_LAUNCH                replay the graph on the stream
!   CALL GRAPH_SYNC                  wait for the stream
!   CALL GRAPH_DESTROY
!
!   CALL GRAPH_ONES (U, V)           U (:, 1) = 1, U (:, 2:) = 0, V = 1, on the host and the device
!                                    (U and V are arrays of the allocator, present on the device)
! U is (GEMM_M, GEMM_K), V is (GEMM_K, >= N); X has GEMM_M * N elements. The values stay exact.

USE ISO_C_BINDING
USE PARKIND1, ONLY : JPIM, JPRM

IMPLICIT NONE

PRIVATE
PUBLIC :: GRAPH_BEGIN, GRAPH_ADD_ONE, GRAPH_END, GRAPH_LAUNCH, GRAPH_SYNC, GRAPH_DESTROY
PUBLIC :: GRAPH_ONES, GEMM_M, GEMM_K

#include "abor1.intfb.h"

INTEGER (KIND=JPIM), PARAMETER :: GEMM_M = 1000, GEMM_K = 16

INTERFACE

INTEGER (KIND=C_INT) FUNCTION HIPSTREAMCREATE (STREAM) BIND (C, NAME='hipStreamCreate')
  IMPORT
  TYPE (C_PTR) :: STREAM
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPSTREAMDESTROY (STREAM) BIND (C, NAME='hipStreamDestroy')
  IMPORT
  TYPE (C_PTR), VALUE :: STREAM
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPSTREAMBEGINCAPTURE (STREAM, MODE) BIND (C, NAME='hipStreamBeginCapture')
  IMPORT
  TYPE (C_PTR), VALUE :: STREAM
  INTEGER (KIND=C_INT), VALUE :: MODE
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPSTREAMENDCAPTURE (STREAM, GRAPH) BIND (C, NAME='hipStreamEndCapture')
  IMPORT
  TYPE (C_PTR), VALUE :: STREAM
  TYPE (C_PTR) :: GRAPH
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPGRAPHGETNODES (GRAPH, NODES, NUMNODES) BIND (C, NAME='hipGraphGetNodes')
  IMPORT
  TYPE (C_PTR), VALUE :: GRAPH, NODES
  INTEGER (KIND=C_SIZE_T) :: NUMNODES
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPGRAPHINSTANTIATEWITHFLAGS (EXEC, GRAPH, FLAGS) &
                            & BIND (C, NAME='hipGraphInstantiateWithFlags')
  IMPORT
  TYPE (C_PTR) :: EXEC
  TYPE (C_PTR), VALUE :: GRAPH
  INTEGER (KIND=C_LONG_LONG), VALUE :: FLAGS
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPGRAPHLAUNCH (EXEC, STREAM) BIND (C, NAME='hipGraphLaunch')
  IMPORT
  TYPE (C_PTR), VALUE :: EXEC, STREAM
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPSTREAMSYNCHRONIZE (STREAM) BIND (C, NAME='hipStreamSynchronize')
  IMPORT
  TYPE (C_PTR), VALUE :: STREAM
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPGRAPHEXECDESTROY (EXEC) BIND (C, NAME='hipGraphExecDestroy')
  IMPORT
  TYPE (C_PTR), VALUE :: EXEC
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPGRAPHDESTROY (GRAPH) BIND (C, NAME='hipGraphDestroy')
  IMPORT
  TYPE (C_PTR), VALUE :: GRAPH
END FUNCTION

TYPE (C_PTR) FUNCTION HIPGETERRORSTRING (IERR) BIND (C, NAME='hipGetErrorString')
  IMPORT
  INTEGER (KIND=C_INT), VALUE :: IERR
END FUNCTION

! hipBLAS (hipblas/hipblas.h); alpha and beta on the host (default pointer mode)
INTEGER (KIND=C_INT) FUNCTION HIPBLASCREATE (HANDLE) BIND (C, NAME='hipblasCreate')
  IMPORT
  TYPE (C_PTR) :: HANDLE
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPBLASDESTROY (HANDLE) BIND (C, NAME='hipblasDestroy')
  IMPORT
  TYPE (C_PTR), VALUE :: HANDLE
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPBLASSETSTREAM (HANDLE, STREAM) BIND (C, NAME='hipblasSetStream')
  IMPORT
  TYPE (C_PTR), VALUE :: HANDLE, STREAM
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION HIPBLASSGEMM (HANDLE, TRANSA, TRANSB, M, N, K, ALPHA, A, LDA, B, LDB, &
                                          & BETA, C, LDC) BIND (C, NAME='hipblasSgemm')
  IMPORT
  TYPE (C_PTR), VALUE :: HANDLE
  INTEGER (KIND=C_INT), VALUE :: TRANSA, TRANSB, M, N, K, LDA, LDB, LDC
  REAL (KIND=C_FLOAT) :: ALPHA, BETA
  TYPE (C_PTR), VALUE :: A, B, C
END FUNCTION

END INTERFACE

INTEGER (KIND=C_INT), PARAMETER :: HIPSTREAMCAPTUREMODEGLOBAL = 0   ! hip/hip_runtime_api.h
INTEGER (KIND=C_INT), PARAMETER :: HIPBLAS_OP_N = 111                ! hipblas-common/hipblas-common.h
TYPE (C_PTR) :: YSTREAM = C_NULL_PTR, YHANDLE = C_NULL_PTR, YGRAPH = C_NULL_PTR, YEXEC = C_NULL_PTR

CONTAINS

SUBROUTINE GRAPH_BEGIN

CALL CKRT (HIPSTREAMCREATE (YSTREAM), 'hipStreamCreate')
CALL CKBL (HIPBLASCREATE (YHANDLE), 'hipblasCreate')
CALL CKBL (HIPBLASSETSTREAM (YHANDLE, YSTREAM), 'hipblasSetStream')
CALL CKRT (HIPSTREAMBEGINCAPTURE (YSTREAM, HIPSTREAMCAPTUREMODEGLOBAL), 'hipStreamBeginCapture')

END SUBROUTINE GRAPH_BEGIN

SUBROUTINE GRAPH_ONES (U, V)

REAL (KIND=JPRM), TARGET, CONTIGUOUS, INTENT (INOUT) :: U (:,:), V (:,:)

U (:, 1) = 1.
U (:, 2:) = 0.
V = 1.
!$OMP TARGET UPDATE TO (U, V)

END SUBROUTINE GRAPH_ONES

SUBROUTINE GRAPH_ADD_ONE (X, U, V)

REAL (KIND=JPRM), TARGET, CONTIGUOUS, INTENT (INOUT) :: X (:), U (:,:), V (:,:)

INTEGER (KIND=C_INT) :: IN
REAL (KIND=C_FLOAT) :: ZONE

IF (MOD (SIZE (X), GEMM_M) /= 0 .OR. SIZE (U, 1) /= GEMM_M .OR. SIZE (U, 2) /= GEMM_K .OR. &
  & SIZE (V, 1) /= GEMM_K .OR. SIZE (V, 2) < SIZE (X) / GEMM_M) CALL ABOR1 ('GRAPH_ADD_ONE: wrong sizes')
IN = INT (SIZE (X) / GEMM_M, C_INT)
ZONE = 1.
! X (M, N) = 1 * U (M, K) * V (K, N) + 1 * X (M, N), on device addresses
!$OMP TARGET DATA USE_DEVICE_ADDR (X, U, V)
CALL CKBL (HIPBLASSGEMM (YHANDLE, HIPBLAS_OP_N, HIPBLAS_OP_N, INT (GEMM_M, C_INT), IN, INT (GEMM_K, C_INT), &
         & ZONE, C_LOC (U), INT (GEMM_M, C_INT), C_LOC (V), INT (GEMM_K, C_INT), ZONE, C_LOC (X), &
         & INT (GEMM_M, C_INT)), 'hipblasSgemm')
!$OMP END TARGET DATA

END SUBROUTINE GRAPH_ADD_ONE

SUBROUTINE GRAPH_END (KNODES)

INTEGER, INTENT (OUT) :: KNODES

INTEGER (KIND=C_SIZE_T) :: INODES

CALL CKRT (HIPSTREAMENDCAPTURE (YSTREAM, YGRAPH), 'hipStreamEndCapture')
CALL CKRT (HIPGRAPHGETNODES (YGRAPH, C_NULL_PTR, INODES), 'hipGraphGetNodes')
CALL CKRT (HIPGRAPHINSTANTIATEWITHFLAGS (YEXEC, YGRAPH, 0_C_LONG_LONG), 'hipGraphInstantiate')
KNODES = INT (INODES)

END SUBROUTINE GRAPH_END

SUBROUTINE GRAPH_LAUNCH

CALL CKRT (HIPGRAPHLAUNCH (YEXEC, YSTREAM), 'hipGraphLaunch')

END SUBROUTINE GRAPH_LAUNCH

SUBROUTINE GRAPH_SYNC

CALL CKRT (HIPSTREAMSYNCHRONIZE (YSTREAM), 'hipStreamSynchronize')

END SUBROUTINE GRAPH_SYNC

SUBROUTINE GRAPH_DESTROY

CALL CKRT (HIPGRAPHEXECDESTROY (YEXEC), 'hipGraphExecDestroy')
CALL CKRT (HIPGRAPHDESTROY (YGRAPH), 'hipGraphDestroy')
CALL CKBL (HIPBLASDESTROY (YHANDLE), 'hipblasDestroy')
CALL CKRT (HIPSTREAMDESTROY (YSTREAM), 'hipStreamDestroy')

END SUBROUTINE GRAPH_DESTROY

SUBROUTINE CKBL (KRC, CDWHAT)

! Abort if a hipBLAS call failed (hipblasStatus_t)

INTEGER (KIND=C_INT), INTENT (IN) :: KRC
CHARACTER (LEN=*), INTENT (IN) :: CDWHAT

CHARACTER (LEN=128) :: CLMESS

IF (KRC == 0) RETURN
WRITE (CLMESS, '(A,A,I0)') CDWHAT, ' failed: hipblasStatus_t ', KRC
CALL ABOR1 (TRIM (CLMESS))

END SUBROUTINE CKBL

SUBROUTINE CKRT (KRC, CDWHAT)

INTEGER (KIND=C_INT), INTENT (IN) :: KRC
CHARACTER (LEN=*), INTENT (IN) :: CDWHAT

CHARACTER (KIND=C_CHAR), POINTER :: CLCH (:)
CHARACTER (LEN=128) :: CLMESS
INTEGER :: J

IF (KRC == 0) RETURN
CLMESS = ''
CALL C_F_POINTER (HIPGETERRORSTRING (KRC), CLCH, [LEN (CLMESS)])
DO J = 1, LEN (CLMESS)
  IF (CLCH (J) == C_NULL_CHAR) EXIT
  CLMESS (J:J) = CLCH (J)
ENDDO
CALL ABOR1 (CDWHAT//' failed: '//TRIM (CLMESS))

END SUBROUTINE CKRT

END MODULE HIP_GRAPH_MOD

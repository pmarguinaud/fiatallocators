PROGRAM TEST_ADDRESSES

! Test c: the same sequence of allocations, repeated ("time steps"), gives the same addresses,
! on both sides, with arrays of several types and sizes.

USE ISO_C_BINDING
USE PARKIND1, ONLY : JPIM, JPIB, JPRM, JPRD
USE ALLOCATOR_BASE_MOD, ONLY : ALLOCATOR_BASE, SIDE_LOWER, SIDE_UPPER
USE TEST_UTIL_MOD, ONLY : TEST_SETUP, CHECK, TEST_END

IMPLICIT NONE

CLASS (ALLOCATOR_BASE), POINTER :: YLALLOC
CHARACTER (LEN=16) :: CLKIND
LOGICAL :: LLGPU
INTEGER, PARAMETER :: NSTEP = 3
INTEGER (KIND=C_INTPTR_T) :: IADDR (6, NSTEP)
INTEGER :: JSTEP

CALL TEST_SETUP ('test_addresses', YLALLOC, CLKIND, LLGPU)

DO JSTEP = 1, NSTEP
  CALL STEP (IADDR (:, JSTEP))
ENDDO
DO JSTEP = 2, NSTEP
  CALL CHECK (ALL (IADDR (:, JSTEP) == IADDR (:, 1)), 'same addresses at every step')
ENDDO

CALL TEST_END (YLALLOC)

CONTAINS

SUBROUTINE STEP (KADDR)

! One "time step": a nested sequence of allocations on both sides

INTEGER (KIND=C_INTPTR_T), INTENT (OUT) :: KADDR (6)

REAL (KIND=JPRD), POINTER :: ZA (:,:), ZC (:)
REAL (KIND=JPRM), POINTER :: ZB (:,:,:)
INTEGER (KIND=JPIM), POINTER :: IX (:)
INTEGER (KIND=JPIB), POINTER :: IY (:,:)
REAL (KIND=JPRD), POINTER :: ZD (:)

CALL YLALLOC%ALLOCATE (ZA, [1000, 37])
CALL YLALLOC%ALLOCATE (ZB, [17, 33, 5], KSIDE=SIDE_UPPER)
CALL YLALLOC%ALLOCATE (IX, [12345])
CALL YLALLOC%ALLOCATE (IY, [100, 100], KSIDE=SIDE_UPPER)
CALL YLALLOC%ALLOCATE (ZC, [999999])
KADDR (1) = TRANSFER (C_LOC (ZA), KADDR (1))
KADDR (2) = TRANSFER (C_LOC (ZB), KADDR (1))
KADDR (3) = TRANSFER (C_LOC (IX), KADDR (1))
KADDR (4) = TRANSFER (C_LOC (IY), KADDR (1))
KADDR (5) = TRANSFER (C_LOC (ZC), KADDR (1))
CALL YLALLOC%DEALLOCATE (ZC)
CALL YLALLOC%ALLOCATE (ZD, [50000], KSIDE=SIDE_UPPER)
KADDR (6) = TRANSFER (C_LOC (ZD), KADDR (1))
CALL YLALLOC%DEALLOCATE (ZD)
CALL YLALLOC%DEALLOCATE (IY)
CALL YLALLOC%DEALLOCATE (IX)
CALL YLALLOC%DEALLOCATE (ZB)
CALL YLALLOC%DEALLOCATE (ZA)

END SUBROUTINE STEP

END PROGRAM TEST_ADDRESSES

MODULE TEST_UTIL_MOD

! Helpers for the tests. Every test program takes two arguments:
!   <kind> <side>     kind: doublestack, fixed or peak; side: cpu or gpu
! and creates the allocator with NEW_ALLOCATOR.

USE PARKIND1, ONLY : JPIB
USE ALLOCATOR_BASE_MOD, ONLY : ALLOCATOR_BASE
USE NEW_ALLOCATOR_MOD, ONLY : NEW_ALLOCATOR

IMPLICIT NONE

PRIVATE
PUBLIC :: TEST_SETUP, CHECK, TEST_END, NFAIL

#include "abor1.intfb.h"

INTEGER :: NFAIL = 0
CHARACTER (LEN=64) :: CNAME = ''

CONTAINS

SUBROUTINE TEST_SETUP (CDPROG, YDALLOC, CDKIND, LDGPU, KSIZE, LDDEBUG, LDVERBOSE)

! Read <kind> <cpu|gpu> from the command line, create the allocator.
! KSIZE: size given to INIT; default 256 MiB for 'fixed', 0 otherwise.

CHARACTER (LEN=*), INTENT (IN) :: CDPROG
CLASS (ALLOCATOR_BASE), POINTER, INTENT (OUT) :: YDALLOC
CHARACTER (LEN=*), INTENT (OUT) :: CDKIND
LOGICAL, INTENT (OUT) :: LDGPU
INTEGER (KIND=JPIB), INTENT (IN), OPTIONAL :: KSIZE
LOGICAL, INTENT (IN), OPTIONAL :: LDDEBUG, LDVERBOSE

CHARACTER (LEN=16) :: CLSIDE
INTEGER (KIND=JPIB) :: ISIZE

IF (COMMAND_ARGUMENT_COUNT () /= 2) CALL ABOR1 (CDPROG//': usage: '//CDPROG//' <doublestack|fixed|peak> <cpu|gpu>')
CALL GET_COMMAND_ARGUMENT (1, CDKIND)
CALL GET_COMMAND_ARGUMENT (2, CLSIDE)
LDGPU = CLSIDE == 'gpu'
ISIZE = MERGE (256_JPIB * 1024_JPIB * 1024_JPIB, 0_JPIB, CDKIND == 'fixed')
IF (PRESENT (KSIZE)) ISIZE = KSIZE
CNAME = CDPROG//' '//TRIM (CDKIND)//' '//TRIM (CLSIDE)
PRINT '(A,A)', 'TEST ', TRIM (CNAME)
CALL NEW_ALLOCATOR (YDALLOC, TRIM (CDKIND), LDGPU, ISIZE, LDDEBUG, LDVERBOSE)

END SUBROUTINE TEST_SETUP

SUBROUTINE CHECK (LDOK, CDWHAT)

LOGICAL, INTENT (IN) :: LDOK
CHARACTER (LEN=*), INTENT (IN) :: CDWHAT

IF (.NOT. LDOK) THEN
  NFAIL = NFAIL + 1
  PRINT '(A,A)', 'FAILED: ', CDWHAT
ENDIF

END SUBROUTINE CHECK

SUBROUTINE TEST_END (YDALLOC)

CLASS (ALLOCATOR_BASE), POINTER, INTENT (INOUT) :: YDALLOC

CALL YDALLOC%DESTROY
DEALLOCATE (YDALLOC)
IF (NFAIL > 0) THEN
  PRINT '(A,I0,A,A)', 'TEST FAILED (', NFAIL, ' checks): ', TRIM (CNAME)
  CALL ABOR1 ('test failed')
ENDIF
PRINT '(A,A)', 'TEST PASSED: ', TRIM (CNAME)

END SUBROUTINE TEST_END

END MODULE TEST_UTIL_MOD

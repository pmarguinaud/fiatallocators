PROGRAM TEST_PEAK

! Test g: PEAK_USED and the report printed by DESTROY.
!   10 MiB (lower), 30 MiB (upper), free 10 MiB, 5 MiB (lower): peak 40 MiB of arrays.
! The stack-based allocators round each array up to ALLOC_ALIGNMENT bytes; these sizes are
! multiples of it, so every allocator reports exactly 40 MiB.

USE PARKIND1, ONLY : JPIB, JPRM
USE ALLOCATOR_BASE_MOD, ONLY : ALLOCATOR_BASE, SIDE_UPPER
USE TEST_UTIL_MOD, ONLY : TEST_SETUP, CHECK, TEST_END

IMPLICIT NONE

CLASS (ALLOCATOR_BASE), POINTER :: YLALLOC
CHARACTER (LEN=16) :: CLKIND
LOGICAL :: LLGPU
REAL (KIND=JPRM), POINTER :: Z10 (:), Z30 (:), Z5 (:)
INTEGER (KIND=JPIB), PARAMETER :: MIB = 1024_JPIB * 1024_JPIB

CALL TEST_SETUP ('test_peak', YLALLOC, CLKIND, LLGPU, LDVERBOSE=.TRUE.)

CALL YLALLOC%ALLOCATE (Z10, [INT (10 * MIB / 4)])
CALL YLALLOC%ALLOCATE (Z30, [INT (30 * MIB / 4)], KSIDE=SIDE_UPPER)
CALL YLALLOC%DEALLOCATE (Z10)
CALL YLALLOC%ALLOCATE (Z5, [INT (5 * MIB / 4)])
CALL CHECK (YLALLOC%PEAK_USED () == 40 * MIB, 'peak is 40 MiB')
PRINT '(A,I0)', 'PEAK_USED: ', YLALLOC%PEAK_USED ()
CALL YLALLOC%DEALLOCATE (Z5)
CALL YLALLOC%DEALLOCATE (Z30)

CALL TEST_END (YLALLOC)

END PROGRAM TEST_PEAK

MODULE CUDA_GRAPH_MOD

! Minimal CUDA graph interface for the tests (NVIDIA): capture the kernels launched on an OpenACC
! async queue, replay them. The AMD tests will use HIP graphs (hipStreamBeginCapture, ...).
!
!   CALL GRAPH_BEGIN (KQUEUE)     start capturing the CUDA stream of OpenACC queue KQUEUE
!   CALL GRAPH_END (KNODES)       end the capture, instantiate; KNODES: number of nodes captured
!   CALL GRAPH_LAUNCH             replay the graph on the stream
!   CALL GRAPH_SYNC               wait for the stream
!   CALL GRAPH_DESTROY

USE ISO_C_BINDING

IMPLICIT NONE

PRIVATE
PUBLIC :: GRAPH_BEGIN, GRAPH_END, GRAPH_LAUNCH, GRAPH_SYNC, GRAPH_DESTROY

#include "abor1.intfb.h"

INTERFACE

TYPE (C_PTR) FUNCTION ACC_GET_CUDA_STREAM_C (IASYNC) BIND (C, NAME='acc_get_cuda_stream')
  IMPORT
  INTEGER (KIND=C_LONG_LONG), VALUE :: IASYNC
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUDASTREAMBEGINCAPTURE (STREAM, MODE) BIND (C, NAME='cudaStreamBeginCapture')
  IMPORT
  TYPE (C_PTR), VALUE :: STREAM
  INTEGER (KIND=C_INT), VALUE :: MODE
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUDASTREAMENDCAPTURE (STREAM, GRAPH) BIND (C, NAME='cudaStreamEndCapture')
  IMPORT
  TYPE (C_PTR), VALUE :: STREAM
  TYPE (C_PTR) :: GRAPH
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUDAGRAPHGETNODES (GRAPH, NODES, NUMNODES) BIND (C, NAME='cudaGraphGetNodes')
  IMPORT
  TYPE (C_PTR), VALUE :: GRAPH, NODES
  INTEGER (KIND=C_SIZE_T) :: NUMNODES
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUDAGRAPHINSTANTIATEWITHFLAGS (EXEC, GRAPH, FLAGS) &
                            & BIND (C, NAME='cudaGraphInstantiateWithFlags')
  IMPORT
  TYPE (C_PTR) :: EXEC
  TYPE (C_PTR), VALUE :: GRAPH
  INTEGER (KIND=C_LONG_LONG), VALUE :: FLAGS
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUDAGRAPHLAUNCH (EXEC, STREAM) BIND (C, NAME='cudaGraphLaunch')
  IMPORT
  TYPE (C_PTR), VALUE :: EXEC, STREAM
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUDASTREAMSYNCHRONIZE (STREAM) BIND (C, NAME='cudaStreamSynchronize')
  IMPORT
  TYPE (C_PTR), VALUE :: STREAM
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUDAGRAPHEXECDESTROY (EXEC) BIND (C, NAME='cudaGraphExecDestroy')
  IMPORT
  TYPE (C_PTR), VALUE :: EXEC
END FUNCTION

INTEGER (KIND=C_INT) FUNCTION CUDAGRAPHDESTROY (GRAPH) BIND (C, NAME='cudaGraphDestroy')
  IMPORT
  TYPE (C_PTR), VALUE :: GRAPH
END FUNCTION

TYPE (C_PTR) FUNCTION CUDAGETERRORSTRING (IERR) BIND (C, NAME='cudaGetErrorString')
  IMPORT
  INTEGER (KIND=C_INT), VALUE :: IERR
END FUNCTION

END INTERFACE

INTEGER (KIND=C_INT), PARAMETER :: CUDASTREAMCAPTUREMODERELAXED = 2
TYPE (C_PTR) :: YSTREAM = C_NULL_PTR, YGRAPH = C_NULL_PTR, YEXEC = C_NULL_PTR

CONTAINS

SUBROUTINE GRAPH_BEGIN (KQUEUE)

INTEGER, INTENT (IN) :: KQUEUE

YSTREAM = ACC_GET_CUDA_STREAM_C (INT (KQUEUE, C_LONG_LONG))
CALL CKRT (CUDASTREAMBEGINCAPTURE (YSTREAM, CUDASTREAMCAPTUREMODERELAXED), 'cudaStreamBeginCapture')

END SUBROUTINE GRAPH_BEGIN

SUBROUTINE GRAPH_END (KNODES)

INTEGER, INTENT (OUT) :: KNODES

INTEGER (KIND=C_SIZE_T) :: INODES

CALL CKRT (CUDASTREAMENDCAPTURE (YSTREAM, YGRAPH), 'cudaStreamEndCapture')
CALL CKRT (CUDAGRAPHGETNODES (YGRAPH, C_NULL_PTR, INODES), 'cudaGraphGetNodes')
CALL CKRT (CUDAGRAPHINSTANTIATEWITHFLAGS (YEXEC, YGRAPH, 0_C_LONG_LONG), 'cudaGraphInstantiate')
KNODES = INT (INODES)

END SUBROUTINE GRAPH_END

SUBROUTINE GRAPH_LAUNCH

CALL CKRT (CUDAGRAPHLAUNCH (YEXEC, YSTREAM), 'cudaGraphLaunch')

END SUBROUTINE GRAPH_LAUNCH

SUBROUTINE GRAPH_SYNC

CALL CKRT (CUDASTREAMSYNCHRONIZE (YSTREAM), 'cudaStreamSynchronize')

END SUBROUTINE GRAPH_SYNC

SUBROUTINE GRAPH_DESTROY

CALL CKRT (CUDAGRAPHEXECDESTROY (YEXEC), 'cudaGraphExecDestroy')
CALL CKRT (CUDAGRAPHDESTROY (YGRAPH), 'cudaGraphDestroy')

END SUBROUTINE GRAPH_DESTROY

SUBROUTINE CKRT (KRC, CDWHAT)

INTEGER (KIND=C_INT), INTENT (IN) :: KRC
CHARACTER (LEN=*), INTENT (IN) :: CDWHAT

CHARACTER (KIND=C_CHAR), POINTER :: CLCH (:)
CHARACTER (LEN=128) :: CLMESS
INTEGER :: J

IF (KRC == 0) RETURN
CLMESS = ''
CALL C_F_POINTER (CUDAGETERRORSTRING (KRC), CLCH, [LEN (CLMESS)])
DO J = 1, LEN (CLMESS)
  IF (CLCH (J) == C_NULL_CHAR) EXIT
  CLMESS (J:J) = CLCH (J)
ENDDO
CALL ABOR1 (CDWHAT//' failed: '//TRIM (CLMESS))

END SUBROUTINE CKRT

END MODULE CUDA_GRAPH_MOD

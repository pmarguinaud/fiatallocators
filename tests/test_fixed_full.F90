PROGRAM TEST_FIXED_FULL

! Test g: FIXED_* with a 1 MiB buffer; an allocation of 2 MiB must abort with a clear message.
! Expected to FAIL (ABOR1); registered with WILL_FAIL.

USE PARKIND1, ONLY : JPIB, JPRM
USE ALLOCATOR_BASE_MOD, ONLY : ALLOCATOR_BASE
USE TEST_UTIL_MOD, ONLY : TEST_SETUP, TEST_END

IMPLICIT NONE

CLASS (ALLOCATOR_BASE), POINTER :: YLALLOC
CHARACTER (LEN=16) :: CLKIND
LOGICAL :: LLGPU
REAL (KIND=JPRM), POINTER :: Z (:)

CALL TEST_SETUP ('test_fixed_full', YLALLOC, CLKIND, LLGPU, KSIZE=1024_JPIB * 1024_JPIB)
CALL YLALLOC%ALLOCATE (Z, [512 * 1024])     ! 2 MiB
PRINT '(A)', 'no abort: full buffer not detected'
CALL TEST_END (YLALLOC)

END PROGRAM TEST_FIXED_FULL
